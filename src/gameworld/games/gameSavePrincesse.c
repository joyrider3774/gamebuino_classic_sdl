#define SAVEP_STATE_TITLE 0
#define SAVEP_STATE_PLAYING 1
#define SAVEP_STATE_VICTORY 2

int savepState;
int savepXpos;
int savepXposMe;
int savepAttkmechant;

void savepInitGame()
{
    savepXpos = 0;
    savepXposMe = 16;
    savepAttkmechant = 0;
}

void savepUpdateTitle()
{
    gbSetColor( 1 );
    gbCursorX = 4;
    gbCursorY = 16;
    gbPrintString( "Sauve la princesse" );
    gbCursorX = 4;
    gbCursorY = 32;
    gbPrintString( "PRESS A" );

    if( gbPressed( BTN_A ) )
    {
        savepInitGame();
        savepState = SAVEP_STATE_PLAYING;
    }
}

void savepUpdateVictory()
{
    gbCursorX = 0;
    gbCursorY = 0;
    gbPrintString( "Youhou !\nappuis sur A" );

    if( gbPressed( BTN_A ) )
    {
        savepInitGame();
        savepState = SAVEP_STATE_TITLE;
    }
}

void savepUpdatePlaying()
{
    if( gbPressed( BTN_C ) )
    {
        savepInitGame();
        savepState = SAVEP_STATE_TITLE;
        return;
    }

    gbDrawBitmap( 0, 0, savepWorldBitmap );

    if( gbRepeat( BTN_RIGHT, 1 ) )
    {
        if( !gbCollideBitmapBitmap( savepXpos, 28, savepPrince1Bitmap, savepXposMe, 28, savepMechant1Bitmap ) )
          savepXpos++;
    }
    else if( gbRepeat( BTN_LEFT, 1 ) )
    {
        savepXpos--;
    }
    if( savepXpos < 0 ) savepXpos = 0;
    if( savepXpos > 72 ) savepXpos = 72;

    if( gbRepeat( BTN_A, 1 ) )
    {
        gbDrawBitmap( savepXpos, 28, savepPrince1Bitmap );
        gbPlayTick();
    }
    else
    {
        gbDrawBitmap( savepXpos, 28, savepPrinceBitmap );
    }
    if( gbPressed( BTN_A ) && gbCollideBitmapBitmap( savepXpos, 28, savepPrince1Bitmap, savepXposMe, 28, savepMechant1Bitmap ) )
    {
        savepXposMe += 4;
        gbPlayOK();
    }

    if( savepAttkmechant )
      gbDrawBitmap( savepXposMe, 28, savepMechant1Bitmap );
    else
      gbDrawBitmap( savepXposMe, 28, savepMechantBitmap );

    if( !gbCollideBitmapBitmap( savepXpos, 28, savepPrince1Bitmap, savepXposMe, 28, savepMechant1Bitmap ) )
      savepXposMe--;

    if( arand( 6 ) == 0 )
    {
        savepAttkmechant = !savepAttkmechant;
        if( savepAttkmechant && gbCollideBitmapBitmap( savepXpos, 28, savepPrince1Bitmap, savepXposMe, 28, savepMechant1Bitmap ) )
        {
            savepXpos -= 4;
            savepXposMe -= 1;
            gbPlayOK();
        }
    }

    if( savepXposMe < savepXpos )
      savepXposMe = savepXpos + 10;

    if( savepXpos > 66 && gbPressed( BTN_B ) )
      savepState = SAVEP_STATE_VICTORY;
}

void gameSavePrincesse_init()
{
    gbBegin();
    savepState = SAVEP_STATE_TITLE;
    savepInitGame();
}

void gameSavePrincesse_update()
{
    if( !gbUpdate() ) return;

    if( savepState == SAVEP_STATE_PLAYING )
      savepUpdatePlaying();
    else if( savepState == SAVEP_STATE_TITLE )
      savepUpdateTitle();
    else
      savepUpdateVictory();

    gbRenderFrame();
}
