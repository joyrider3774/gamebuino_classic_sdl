// SavePrincesse ("Sauve la princesse", Clement83, none specified). A
// tiny knight-vs-monster teaching game: walk a knight right across the
// screen toward a castle door, swinging a sword (Button A) to push back
// a monster blocking the way, then press Button B at the door to win.
// Real upstream source and comments are in French - preserved verbatim,
// including the real win screen's own French text ("Youhou !"/"appuis
// sur A" - "press A"), not translated.
//
// Every real `gb.x.y(...)` call site was mechanically rewritten to a
// plain `gbY(...)` function call (this dialect has no classes/methods -
// see gamePong.c's own header comment). `gb.collideBitmapBitmap()` ->
// `gbCollideBitmapBitmap()` directly - a real, already-shipped shim
// primitive, not something this port needed to work around.
//
// REAL BITMAP ART: all 5 real upstream bitmaps (`Mechant`/`Mechant1` -
// the monster idle/attacking, `prince`/`prince1` - the knight idle/
// attacking, `WorldSmall` - the 88x44 full-screen background) were
// already stored as real `0x`-hex byte literals upstream (no
// `B01111111`-style binary literals needing conversion this time) -
// copied byte-for-byte into `int[]` arrays with their own real width/
// height headers preserved, not hand-redrawn.
//
// BLOCKING `gb.titleScreen(F("Sauve la princesse"))` -> EXPLICIT STATE:
// upstream's own real `goTitleScreen()` (called from `setup()` at real
// boot, and again from `loop()` any time Button C is pressed mid-game)
// blocks on this real widget then immediately calls `initGame()` to
// reset knight/monster positions - ported as `SAVEP_STATE_TITLE`, the
// same "blocking widget -> explicit resumable state" treatment used
// throughout this project (see gamePong.c's own header comment); a
// fresh Button A press both resets game state and starts play, matching
// upstream's own real `goTitleScreen()->initGame()` call chain exactly.
// `victorie()` (a second real blocking `while(true)` win-screen loop)
// became `SAVEP_STATE_VICTORY` the same way - dismissing it with Button
// A returns to `SAVEP_STATE_TITLE` and re-runs the same reset, matching
// upstream's own real `victorie(); goTitleScreen();` call chain.
//
// Real upstream quirk preserved exactly, not "fixed": the monster's own
// hit/attack collision checks always use the *attacking*-pose bitmaps
// (`prince1`/`Mechant1`) for hit-testing regardless of which pose is
// actually being drawn that frame (even when the knight/monster are
// shown in their idle pose) - a real, deliberate-looking "always use the
// widest hitbox" simplification in the original source, reproduced
// bit-for-bit via the same fixed bitmap arguments at every
// `gbCollideBitmapBitmap()` call site below.

