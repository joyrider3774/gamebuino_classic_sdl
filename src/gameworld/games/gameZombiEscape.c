void gameZombiEscape_init()
{
    gbBegin();
    zombBeginTitle();
}

void gameZombiEscape_update()
{
    if( !gbUpdate() ) return;

    if( zombState == ZOMB_STATE_TITLE ) zombUpdateTitle();
    else if( zombState == ZOMB_STATE_GAME ) zombUpdateGame();
    else if( zombState == ZOMB_STATE_GAMEOVER ) zombUpdateGameOver();
    else zombUpdateVictory();

    gbRenderFrame();
}
