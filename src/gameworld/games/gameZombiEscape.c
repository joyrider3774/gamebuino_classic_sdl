// ZombiEscape (Frakasss, no license specified,
// github.com/Frakasss/ZombiEscape). A horizontal side-scrolling zombie
// shooter: walk/aim left or right through a multi-screen-wide level,
// shoot approaching zombies with a 6-round weapon (reload with Button B),
// survive their bite damage, and reach the far edge of each of 3 levels'
// world to advance (the last level's exit is a genuine victory screen
// instead of another level).
//
// Every real `gb.x.y(...)` call site was mechanically rewritten to a
// flat `gbY(...)` call (this dialect has no classes/methods - see
// gamebuinoShim.h's own header comment): `gb.display.drawBitmap(...)` ->
// `gbDrawBitmap(...)`/`gbDrawBitmapRotated(...)` (upstream's own
// `NOROT, FLIPH` third/fourth arguments map directly onto this shim's
// own `rotation=0, flip=1` integers), `gb.display.drawPixel(...)` ->
// `gbDrawPixel(...)`, `gb.display.cursorX =`/`cursorY =` ported
// unchanged (gbCursorX/gbCursorY are themselves plain globals here too),
// `gb.display.print()`/`println()` -> `gbPrintString()`/`gbPrintNumber()`
// (this dialect has no function overloading, so real Print's single
// overloaded print() needed splitting into two - println()'s only real
// difference, advancing cursorY afterward, is irrelevant here since
// nothing else is drawn on the same line afterward at either call site),
// `gb.buttons.pressed/repeat(...)` -> `gbPressed()`/`gbRepeat()` (upstream's
// own literal `gb.buttons.repeat(BTN_x, 1)` calls are preserved as literal
// `gbRepeat(BTN_x, 1)` calls - real `Buttons::repeat(btn,1)` means "fire
// every single held frame", which is exactly the continuous per-frame
// movement upstream wants here), `gb.sound.playTick()` -> `gbPlayTick()`,
// `random(min,max)` -> `min + arand(max-min)` (this dialect's own
// established ranged-RNG idiom, matching every other port's own
// `random()` rewrite), `abs(...)` -> `gbAbsInt(...)` (already defined in
// gamebuinoShim.c and used directly by gamePong.c's own real port, despite
// not being declared in gamebuinoShim.h - see this file's own "shim gaps"
// paragraph below), and `F("...")` string-literal wrapping dropped
// (PROGMEM string storage is meaningless here - every other ported game
// already does this). `gb.battery.show = false;` was dropped outright,
// same as every other port (purely cosmetic on real hardware, no
// equivalent here).
//
// Upstream's own blocking `gb.titleScreen(Welcome)` (called once from
// setup() via goTitleScreen(), and again from mid-play on a genuine
// Button-C "give up and return to the title" press) and its own two
// blocking `while(true){ if(gb.update()){ ... } }` loops (gameOver()/
// victory(), each showing one full-screen bitmap until Button B is
// pressed, then calling goTitleScreen() again) were all converted into
// an explicit top-level state machine (`ZOMB_STATE_TITLE`/`_GAMEOVER`/
// `_VICTORY`/`_GAME`, dismissed by a genuine `gbPressed(BTN_A)`/
// `gbPressed(BTN_B)` on the correct tick - the same "blocking loop ->
// explicit resumable state" treatment used throughout this project, see
// gamePong.c's own header comment for the original worked example).
// Upstream's own `startGame` int flag (already a simple non-blocking
// "showing this level's intro bitmap, waiting for Button A before real
// play begins" sub-state inside its own single gb.update()-driven loop(),
// not a blocking call needing its own top-level state) is kept exactly
// as-is, nested inside `ZOMB_STATE_GAME`, matching upstream's own real
// structure as closely as possible rather than inventing a 5th top-level
// state for something upstream itself never treated as blocking.
//
// Upstream's own `switch(sprite){ case 1: ...; case 25: ... }` in
// displayBackground() became an if/else-if chain (no switch statement
// proven to work in this dialect - see every other ported game's own
// header comment for the same note).
//
// A genuine upstream documentation bug, harmless (comment-only, zero
// behavioral effect either way): the real `meDirection` field's own
// comment reads "true: right false: left", but the real code sets it to
// 0 on a RIGHT press and 1 on a LEFT press, and drawMe() draws the
// default (unflipped) sprite orientation when it's 0/false and the
// horizontally-flipped orientation when it's 1/true - i.e. the real
// behavior is exactly backwards from what the comment claims. Corrected
// in this port's own `zombMeDirection` comment to describe its real
// observed behavior instead of reproducing a backwards comment verbatim
// (unlike the executable-code quirks below, a corrected comment carries
// no risk of "fixing" real gameplay behavior a player could ever notice).
//
// Two harmless dead-code oddities found while reading the source,
// preserved-vs-dropped decisions made explicitly rather than silently
// carried over or silently fixed:
// - `zombiInitialized` is set to 1 in initGame() and never read anywhere
//   else in the entire real source - a genuine write-only/dead variable
//   upstream itself never uses for anything. Kept as a real (unused)
//   global with its one real assignment preserved, exactly matching
//   upstream's own harmless oddity, rather than either quietly deleting
//   it (which would be "fixing" a real, if pointless, piece of upstream
//   code) or pretending it does something it never did.
// - initGame() contains a second, bare `worldZombi[50][7];` statement
//   right after the real `worldZombi` declaration comment - a leftover,
//   no-op expression statement (an out-of-bounds array subscript that is
//   evaluated and its result immediately discarded, never assigned to or
//   read from) that could never have had any observable effect even on
//   real hardware. Dropped rather than reproduced literally, since unlike
//   `zombiInitialized` above this one isn't even a variable with any
//   real value to preserve - it is pure inert leftover syntax, and
//   reproducing a no-op statement verbatim would just look like a fresh
//   copy-paste mistake in this port rather than a documented decision.
// - displayZombi()'s own local `int zombiDirection = 0;` is declared and
//   then never read anywhere in the entire real source (confirmed by
//   grepping the whole upstream .ino for the name - exactly one match,
//   its own declaration). A genuinely inert local with zero possible
//   observable effect even as dead code (unlike `zombiInitialized`
//   above, a global that at least crosses function boundaries) - simply
//   omitted here rather than declared-and-ignored, since a local dead
//   variable carries no equivalent "real hardware did this too" weight
//   worth preserving syntax for.
//
// **A real shim gap flagged for review**: `gbAbsInt()` (used here for
// upstream's own `abs(zombixpos - xposMeInTheWorld)` zombie-aggro-range
// checks) is defined in gamebuinoShim.c but was never declared in
// gamebuinoShim.h - the exact same class of gap this project's own
// CLAUDE.md documents already being found and fixed once before for
// `gbDrawChar()`. Not worked around locally here (gamePong.c's own
// already-shipped, already-verified-working port calls it the same
// direct way, proving the single-translation-unit build links it fine
// even without a header declaration), but flagged per this session's own
// instructions so the missing declaration can be added to
// gamebuinoShim.h for real header-completeness, the same fix already
// applied to gbDrawChar().

