void zombUpdateGame()
{
    if( zombStartGame == 1 )
    {
        if( zombGameLevel == 1 )
          gbDrawBitmap( 0, 0, zombLvl1Bitmap );
        else if( zombGameLevel == 2 )
          gbDrawBitmap( 0, 0, zombLvl2Bitmap );
        else if( zombGameLevel == 3 )
          gbDrawBitmap( 0, 0, zombLvl3Bitmap );

        if( gbPressed( BTN_A ) )
          zombStartGame = 0;
    }
    else
    {
        // --> 0 == zombStartGame

        if( gbPressed( BTN_C ) )
        {
            zombBeginTitle();
            return;
        }

        zombStartStage = ( zombStage - 1 ) * 120;
        zombEndStage = zombStage * 120;
        if( zombEndStage > zombWorldSize )
          zombEndStage = zombWorldSize;
        zombFire = false;

        if( gbPressed( BTN_A ) && zombAmmo > 0 ) // fire!
        {
            gbPlayTick();
            zombFire = true;
            zombAmmo = zombAmmo - 1;
        }

        if( gbRepeat( BTN_RIGHT, 1 ) || gbRepeat( BTN_LEFT, 1 ) || gbRepeat( BTN_UP, 1 ) || gbRepeat( BTN_DOWN, 1 ) )
        {
            if( zombMeWalk == true )
              zombMeWalk = false;
            else
              zombMeWalk = true;
        }

        if( gbRepeat( BTN_UP, 1 ) )
        {
            if( zombYposMe > 15 )
              zombYposMe = zombYposMe - zombMeSpeed;
        }

        if( gbRepeat( BTN_DOWN, 1 ) )
        {
            if( zombYposMe < 36 )
              zombYposMe = zombYposMe + zombMeSpeed;
        }

        if( gbRepeat( BTN_RIGHT, 1 ) )
        {
            zombMeDirection = 0;
            if( zombXposMeInTheWorld > ( zombTmpStartStage + 40 ) && zombXposMeInTheWorld < ( zombEndStage - 40 ) && ( zombXposWorld + 88 ) < zombEndStage )
            {
                zombXposMeInTheWorld = zombXposMeInTheWorld + zombMeSpeed;
                zombXposWorld = zombXposWorld + zombMeSpeed;
                if( zombTmpStartStage < zombStartStage )
                  zombTmpStartStage = zombTmpStartStage + zombMeSpeed;
            }
            else
            {
                if( ( zombXposMeInTheWorld + zombMeSpeed ) <= ( zombEndStage - 8 ) )
                {
                    zombXposMeInTheWorld = zombXposMeInTheWorld + zombMeSpeed;
                    zombXposMe = zombXposMe + zombMeSpeed;
                }
            }
        }
        else if( gbRepeat( BTN_LEFT, 1 ) )
        {
            zombMeDirection = 1;
            if( zombXposMeInTheWorld > ( zombTmpStartStage + 40 ) && zombXposMeInTheWorld < ( zombEndStage - 40 ) && zombXposWorld > zombTmpStartStage )
            {
                zombXposWorld = zombXposWorld - zombMeSpeed;
                zombXposMeInTheWorld = zombXposMeInTheWorld - zombMeSpeed;
            }
            else
            {
                if( ( zombXposMeInTheWorld + zombMeSpeed ) >= zombTmpStartStage )
                {
                    zombXposMe = zombXposMe - zombMeSpeed;
                    zombXposMeInTheWorld = zombXposMeInTheWorld - zombMeSpeed;
                }
            }
        }

        if( gbPressed( BTN_B ) || zombMeReload == true )
        {
            zombMeReload = false;
            if( zombAmmo < 6 )
            {
                zombMeReload = true;
                zombAmmo = zombAmmo + 1;
            }
        }

        if( zombDamage >= ZOMB_MAX_HEALTH )
        {
            zombBeginGameOver();
            return;
        }

        if( ( zombXposMeInTheWorld + 16 ) > zombWorldSize )
        {
            if( zombGameLevel == 3 )
            {
                zombBeginVictory();
                return;
            }
            else
              zombInitGame();
        }

        if( zombTmpStartStage < zombStartStage )
        {
            gbCursorX = 30;
            gbCursorY = 38;
            gbPrintString( "Go =>" );
        }

        zombDisplayBackground();
        if( zombTmpStartStage == zombStartStage )
          zombDisplayZombi();
        zombDisplayLevel();
        zombDisplayAmmo( zombAmmo );
        zombDisplayHealth( zombDamage );
        zombDrawMe();
    }
}

void zombUpdateGameOver()
{
    gbDrawBitmap( 0, 0, zombGameOverBitmap );
    if( gbPressed( BTN_B ) )
      zombBeginTitle();
}

void zombUpdateVictory()
{
    gbDrawBitmap( 0, 0, zombCongratulationBitmap );
    if( gbPressed( BTN_B ) )
      zombBeginTitle();
}

