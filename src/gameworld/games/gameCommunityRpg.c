void crpgTextClearBuf()
{
    int l;
    for( l = 0; l < 4; l++ )
      crpgTextLen[ l ] = 0;
    crpgTextLine = 0;
}

void crpgTextBegin()
{
    crpgTextActive = true;
    crpgTextPhase = 0;
    crpgTextWait = 0;
    crpgTextDelay = 0;
    crpgTextJ = 0;
    crpgTextClearBuf();
}

void crpgTextPutChar( int c )
{
    if( crpgTextLine < 0 ) return;
    if( crpgTextLine >= 4 ) return;
    int n = crpgTextLen[ crpgTextLine ];
    if( n >= 24 ) return;
    crpgTextBuf[ crpgTextLine ][ n ] = c;
    crpgTextLen[ crpgTextLine ] = n + 1;
}

// One tick of the text display. Real upstream types one character per
// delay(100) (= 2 ticks at 20fps), breaks lines on 0xFE, waits for a fresh A
// press on 0xFD (new page) and 0xFF (end).
void crpgTextStep()
{
    bool a = crpgBtn( BTN_A );

    if( crpgTextPhase != 0 )
    {
        // real upstream's `while(pressed); while(!pressed); while(pressed);`,
        // as a live three-stage gate (see this file's own header comment)
        if( crpgTextWait == 0 )
        {
            if( !a ) crpgTextWait = 1;
            return;
        }
        if( crpgTextWait == 1 )
        {
            if( a ) crpgTextWait = 2;
            return;
        }
        if( a ) return;

        if( crpgTextPhase == 2 )
        {
            crpgTextActive = false;
            return;
        }
        crpgTextJ = 0;
        crpgTextClearBuf();
        crpgTextPhase = 0;
        return;
    }

    if( crpgTextJ == 0 )
      if( !a ) crpgTextJ = 1;

    bool fast = false;
    if( crpgTextJ == 1 )
      if( a ) fast = true;

    int budget = 1;
    if( fast ) budget = 4;
    else
    {
        if( crpgTextDelay > 0 )
        {
            crpgTextDelay = crpgTextDelay - 1;
            return;
        }
    }

    int n;
    for( n = 0; n < budget; n++ )
    {
        int c = crpgDatByte( crpgScriptCursor );
        crpgScriptCursor = crpgScriptCursor + 1;

        if( c == 0xFF )
        {
            crpgTextPhase = 2;
            crpgTextWait = 0;
            return;
        }
        if( c == 0xFE )
        {
            crpgTextLine = crpgTextLine + 1;
            continue;
        }
        if( c == 0xFD )
        {
            crpgTextPhase = 1;
            crpgTextWait = 0;
            return;
        }
        crpgTextPutChar( c );
    }

    crpgTextDelay = 1; // 2 ticks per character = real delay(100) at 20fps
}

// Real drawTextBox()'s own frame, drawn on top of the already-drawn scene
void crpgDrawTextBox()
{
    gbSetColor( GB_BLACK );
    gbDrawFastHLine( 4, 31, 76 );
    gbDrawFastHLine( 4, 45, 76 );
    gbDrawFastVLine( 3, 32, 13 );
    gbDrawFastVLine( 80, 32, 13 );
    gbSetColor( GB_WHITE );
    gbFillRect( 4, 32, 76, 13 );
    gbSetColor( GB_BLACK );

    int l, c;
    for( l = 0; l < 4; l++ )
      for( c = 0; c < crpgTextLen[ l ]; c++ )
        gbDrawChar( crpgTextBuf[ l ][ c ], 5 + c * 4, 33 + l * 6 );
}

