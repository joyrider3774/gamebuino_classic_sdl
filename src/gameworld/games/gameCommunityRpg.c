// Real loop()'s own `if (gb.update()) { ... }` body, with the script
// interpreter given first claim on the tick (real upstream's scripts simply
// never returned to loop() at all until they finished - see this file's own
// header comment).
void gameCommunityRpg_update()
{
    if( !gbUpdate() ) return;

    if( crpgScriptActive )
      crpgScriptStep();
    else
    {
        if( crpgPendingStartCursor != 0 )
        {
            crpgScriptCursor = crpgPendingStartCursor;
            crpgPendingStartCursor = 0;
            crpgScriptStart( CRPG_SCTX_START );
        }

        if( !crpgScriptActive )
        {
            int r = crpgPlayerUpdate();
            if( r == 1 )
            {
                int i;
                for( i = 0; i < CRPG_MAX_NUM_ENEMIES; i++ )
                  if( crpgEnemyActive[ i ] != 0 )
                    crpgEnemyUpdate( i );
            }
            else if( r == 0 )
            {
                // real exitTilemap(): the map the player just left may have an
                // exit script that loads a different map itself
                if( crpgExitTilemap() )
                {
                    crpgLoadTilemap( crpgCurrentMap );
                    crpgFocusCam();
                }
            }
        }
    }

    crpgDrawScreen();
    if( crpgTextActive ) crpgDrawTextBox();

    gbRenderFrame();
}
