    int i;
    for( i = 0; i < CRPG_SCRIPT_NUM_VARS; i++ )
      crpgScriptVars[ i ] = 0;
    for( i = 0; i < CRPG_MAX_NUM_ENEMIES; i++ )
      crpgEnemyActive[ i ] = 0;

    crpgTextActive = false;
