void crpgEnemyUpdate( int i )
{
    if( crpgEnemyState[ i ] == 5 )
    {
        crpgEnemyState[ i ] = arand( 5 );
        if( crpgEnemyState[ i ] < 4 ) crpgEnemyDirection[ i ] = crpgEnemyState[ i ];
        crpgEnemyCounter[ i ] = 8 + arand( 8 * 8 - 8 ); // real random(1*8, 8*8)
        return;
    }

    // real `if (!counter--)` on a byte, wraparound included
    int old = crpgEnemyCounter[ i ];
    crpgEnemyCounter[ i ] = ( old - 1 ) & 0xFF;
    if( old == 0 )
    {
        crpgEnemyState[ i ] = 5;
        return;
    }

    int x = crpgEnemyX[ i ];
    int y = crpgEnemyY[ i ];
    int st = crpgEnemyState[ i ];

    if( st == 0 )
    {
        if( crpgGetWalkInfoX( x + 2, y + 4, 4, 4, 1 ) != CRPG_FLAG_TILE_WALKABLE )
        {
            crpgEnemyState[ i ] = 5;
            return;
        }
        crpgEnemyX[ i ] = x + 1;
        return;
    }
    if( st == 1 )
    {
        if( crpgGetWalkInfoY( x + 2, y + 4, 4, 4, -1 ) != CRPG_FLAG_TILE_WALKABLE )
        {
            crpgEnemyState[ i ] = 5;
            return;
        }
        crpgEnemyY[ i ] = y - 1;
        return;
    }
    if( st == 2 )
    {
        if( crpgGetWalkInfoX( x + 2, y + 4, 4, 4, -1 ) != CRPG_FLAG_TILE_WALKABLE )
        {
            crpgEnemyState[ i ] = 5;
            return;
        }
        crpgEnemyX[ i ] = x - 1;
        return;
    }
    if( st == 3 )
    {
        if( crpgGetWalkInfoY( x + 2, y + 4, 4, 4, 1 ) != CRPG_FLAG_TILE_WALKABLE )
        {
            crpgEnemyState[ i ] = 5;
            return;
        }
        crpgEnemyY[ i ] = y + 1;
    }
}

