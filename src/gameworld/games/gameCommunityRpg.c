// Runs opcodes until the script yields a frame (UPDATE_SCREEN), starts
// displaying text, or returns. Called once per tick while a script is active.
void crpgScriptStep()
{
    if( crpgTextActive )
    {
        crpgTextStep();
        if( crpgTextActive ) return;
    }

    int guard = 0;
    while( guard < 4096 )
    {
        guard = guard + 1;

        if( crpgScriptCursor < 0 || crpgScriptCursor >= CRPG_DAT_SIZE )
        {
            // two degenerate script-table entries in the shipped data point
            // one byte past EOF; end cleanly rather than run on garbage
            crpgScriptFinish( true );
            return;
        }

        int op = crpgDatByte( crpgScriptCursor );
        crpgScriptCursor = crpgScriptCursor + 1;

        if( op == CRPG_OP_FADE_TO_WHITE ) continue;   // real LCD contrast fade - no equivalent
        if( op == CRPG_OP_FADE_FROM_WHITE ) continue;

        if( op == CRPG_OP_SET_MAP )
        {
            // real getNum(&currentMap) writes straight into currentMap - it
            // never goes through the variable selector, even when its own
            // operand is a 0x80 <var> reference (getNum saves/restores that)
            crpgCurrentMap = crpgScriptGetNum() & 0xFF;
            crpgLoadTilemap( crpgCurrentMap );
            continue;
        }

        if( op == CRPG_OP_TEXT )
        {
            crpgTextBegin();
            crpgTextStep();
            if( crpgTextActive ) return;
            continue;
        }

        if( op == CRPG_OP_ADD_ENEMY )
        {
            int t = crpgScriptGetNum();
            int idx = crpgAddEnemy( t, 0, 0 );
            // real upstream leaves the two x/y operands unconsumed when the
            // enemy table is full, desynchronising the stream - preserved
            if( idx != 0xFF )
            {
                crpgEnemyX[ idx ] = crpgScriptGetNum();
                crpgEnemyY[ idx ] = crpgScriptGetNum();
            }
            continue;
        }

        if( op == CRPG_OP_FOCUS_CAM )
        {
            crpgFocusCam();
            continue;
        }

        if( op == CRPG_OP_UPDATE_SCREEN )
          return; // yield exactly one frame - see this file's own header comment

        if( op == CRPG_OP_SET_VAR )
        {
            crpgScriptGetVar();
            int v = crpgScriptGetNum();
            crpgScriptVarWrite( v );
            continue;
        }

        if( op == CRPG_OP_JUMP )
        {
            crpgScriptJumpLowByte();
            continue;
        }

        if( op == CRPG_OP_JUMP_IFNOT )
        {
            if( crpgScriptCondition() ) crpgScriptCursor = crpgScriptCursor + 4;
            else crpgScriptJumpLowByte();
            continue;
        }

        if( op == CRPG_OP_JUMP_IF )
        {
            if( crpgScriptCondition() ) crpgScriptJumpLowByte();
            else crpgScriptCursor = crpgScriptCursor + 4;
            continue;
        }

        if( op == CRPG_OP_ADD )
        {
            crpgScriptGetVar();
            int v = crpgScriptGetNum();
            crpgScriptVarWrite( crpgScriptVarRead() + v );
            continue;
        }

        if( op == CRPG_OP_INC )
        {
            crpgScriptGetVar();
            crpgScriptVarWrite( crpgScriptVarRead() + 1 );
            continue;
        }

        if( op == CRPG_OP_DEC )
        {
            crpgScriptGetVar();
            crpgScriptVarWrite( crpgScriptVarRead() - 1 );
            continue;
        }

        if( op == CRPG_OP_CALL )
        {
            crpgScriptCursorCall = crpgScriptCursor + 4;
            crpgScriptJumpLowByte();
            continue;
        }

        if( op == CRPG_OP_RET )
        {
            crpgScriptCursor = crpgScriptCursorCall;
            continue;
        }

        if( op == CRPG_OP_RETURN_FALSE )
        {
            crpgScriptFinish( false );
            return;
        }

        if( op == CRPG_OP_RETURN_TRUE )
        {
            gbClear();
            crpgScriptFinish( true );
            return;
        }

        // any other byte (SCRIPT_NOP included) simply advances the cursor -
        // real upstream's own switch has no default case
    }

    crpgScriptFinish( true );
}

// Real Script::run()'s own entry conditions, plus the caller bookkeeping the
// flattened state machine needs
void crpgScriptStart( int ctx )
{
    crpgScriptCtx = ctx;
    crpgScriptCursorCall = 0;

    if( crpgScriptCursor == 0 )
    {
        gbClear();
        crpgScriptFinish( true );
        return;
    }

    crpgScriptActive = true;
    crpgTextActive = false;
    crpgScriptStep();
}

// Real exitTilemap(). Returns true if the caller should load the next tilemap
// itself; false if a script took over (its own result decides).
bool crpgExitTilemap()
{
    if( crpgMapAddress == 0 ) return true;
    if( ( crpgDatByte( crpgMapAddress ) & 1 ) == 0 ) return true;

    crpgScriptCursor = crpgRead32( crpgMapAddress + CRPG_DATFILE_TILEMAP_SIZE + 4 );
    crpgScriptStart( CRPG_SCTX_EXIT );
    return false;
}

