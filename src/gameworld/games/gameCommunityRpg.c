// Real Script::loadInTilemap(): find the script attached to a given tile
// offset on the current map. Real upstream re-reads the table in 42-entry
// blocks; with the file resident that is a plain linear scan.
void crpgScriptLoadInTilemap( int offset )
{
    int i = CRPG_DATFILE_START_SCRIPT;
    int guard = 0;
    while( guard < 512 )
    {
        guard = guard + 1;
        int b = crpgDatByte( i );
        if( b == 0xFF )
        {
            crpgScriptCursor = 0;
            return;
        }
        if( b == offset )
          if( crpgDatByte( i + 1 ) == crpgCurrentMap )
          {
              crpgScriptCursor = crpgRead32( i + 2 );
              return;
          }
        i = i + 6;
    }
    crpgScriptCursor = 0;
}

// Real Script::getVar(): reads the variable-selector byte at the cursor.
// Upstream leaves a real `byte* ptr` aimed at the selected storage; this
// dialect has no byte pointers, so the selection is an explicit pair.
void crpgScriptGetVar()
{
    int i = crpgDatByte( crpgScriptCursor );
    crpgScriptCursor = crpgScriptCursor + 1;

    if( i == CRPG_VAR_PLAYER_X ) { crpgVarSel = CRPG_SEL_PLAYER_X; return; }
    if( i == CRPG_VAR_PLAYER_Y ) { crpgVarSel = CRPG_SEL_PLAYER_Y; return; }
    if( i == CRPG_VAR_MAP )      { crpgVarSel = CRPG_SEL_MAP; return; }
    if( i == CRPG_VAR_WORLD )    { crpgVarSel = CRPG_SEL_WORLD; return; }

    crpgVarSel = CRPG_SEL_SCRIPTVAR;
    // Real upstream indexes vars[i] with the raw byte and would happily run
    // off its own 1-entry array; clamped here.
    if( i < 0 ) i = 0;
    if( i >= CRPG_SCRIPT_NUM_VARS ) i = CRPG_SCRIPT_NUM_VARS - 1;
    crpgVarIdx = i;
}

// Real `(byte)*ptr` - always an unsigned byte view
int crpgScriptVarRead()
{
    if( crpgVarSel == CRPG_SEL_PLAYER_X ) return crpgPX() & 0xFF;
    if( crpgVarSel == CRPG_SEL_PLAYER_Y ) return crpgPY() & 0xFF;
    if( crpgVarSel == CRPG_SEL_MAP ) return crpgCurrentMap & 0xFF;
    if( crpgVarSel == CRPG_SEL_WORLD ) return crpgCurrentWorld & 0xFF;
    return crpgScriptVars[ crpgVarIdx ] & 0xFF;
}

// Real `*ptr = value` - a single-byte write, which for PLAYER_X/PLAYER_Y
// means the high byte of the 16.8 fixed-point coordinate only
void crpgScriptVarWrite( int v )
{
    v = v & 0xFF;
    if( crpgVarSel == CRPG_SEL_PLAYER_X ) { crpgPlayerX = crpgSetHighByte( crpgPlayerX, v ); return; }
    if( crpgVarSel == CRPG_SEL_PLAYER_Y ) { crpgPlayerY = crpgSetHighByte( crpgPlayerY, v ); return; }
    if( crpgVarSel == CRPG_SEL_MAP ) { crpgCurrentMap = v; return; }
    if( crpgVarSel == CRPG_SEL_WORLD ) { crpgCurrentWorld = v; return; }
    crpgScriptVars[ crpgVarIdx ] = v;
}

// Real Script::getNum(): a plain literal byte, or 0x80 <var> for "the value of
// that variable", or 0x80 0x80 for a literal 0x80. Saves and restores the
// current variable selection exactly like upstream's own ptr2 does, because
// SET_VAR/ADD call getVar() first and then getNum() into the selected slot.
int crpgScriptGetNum()
{
    int v = crpgDatByte( crpgScriptCursor );
    crpgScriptCursor = crpgScriptCursor + 1;

    if( v != 0x80 ) return v;

    int peek = crpgDatByte( crpgScriptCursor );
    if( peek == 0x80 )
    {
        crpgScriptCursor = crpgScriptCursor + 1;
        return 0x80;
    }

    int savedSel = crpgVarSel;
    int savedIdx = crpgVarIdx;
    crpgScriptGetVar();
    v = crpgScriptVarRead();
    crpgVarSel = savedSel;
    crpgVarIdx = savedIdx;
    return v;
}

// Real Script::condition(). Upstream has no return statement for any opcode
// other than SCRIPT_LT - undefined behaviour there, false here.
bool crpgScriptCondition()
{
    int op = crpgDatByte( crpgScriptCursor );
    crpgScriptCursor = crpgScriptCursor + 1;

    if( op == CRPG_OP_LT )
    {
        int a = crpgScriptGetNum();
        int b = crpgScriptGetNum();
        return a < b;
    }
    return false;
}

// Real `readProg((byte*)&cursor, 1)` - one byte into the low end of a
// little-endian uint32_t, so a jump can only move within the current
// 256-byte page (deliberate upstream; see this file's own header comment)
void crpgScriptJumpLowByte()
{
    int b = crpgDatByte( crpgScriptCursor );
    crpgScriptCursor = crpgScriptCursor - ( crpgScriptCursor & 0xFF ) + b;
}

bool crpgExitTilemap();

// Hands a finished script's true/false result back to whichever caller was
// interrupted when it started.
void crpgScriptFinish( bool result )
{
    int ctx = crpgScriptCtx;
    crpgScriptActive = false;
    crpgTextActive = false;
    crpgScriptCtx = CRPG_SCTX_NONE;

    if( ctx == CRPG_SCTX_EXIT )
    {
        if( result )
        {
            crpgLoadTilemap( crpgCurrentMap );
            crpgFocusCam();
        }
        return;
    }

    if( ctx == CRPG_SCTX_IDLE_A )
    {
        // real Player::update() returned `res != 0`, and loop() then took the
        // exitTilemap() branch on false
        if( !result )
          if( crpgExitTilemap() )
          {
              crpgLoadTilemap( crpgCurrentMap );
              crpgFocusCam();
          }
        return;
    }

    if( ctx == CRPG_SCTX_MOVE_X )
    {
        if( result )
        {
            crpgPlayerX = crpgWrap16( crpgPlayerX + crpgPlayerVx );
            crpgFocusCam();
        }
        else
        {
            crpgPlayerVx = 0;
            crpgPlayerVy = 0;
        }
        return;
    }

    if( ctx == CRPG_SCTX_MOVE_Y )
    {
        if( result )
        {
            crpgPlayerY = crpgWrap16( crpgPlayerY + crpgPlayerVy );
            crpgFocusCam();
        }
        else
        {
            crpgPlayerVx = 0;
            crpgPlayerVy = 0;
        }
        return;
    }

    // CRPG_SCTX_START - real upstream discards a start script's result too
}

