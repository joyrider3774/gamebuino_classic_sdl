// Community RPG (Sorunome, license: none specified - no LICENSE file and no
// per-file license header anywhere in github.com/Sorunome/gamebuino-community-rpg;
// author confirmed as "Sorunome <mail@sorunome.de>" from the repo's own single
// commit). A small, genuinely unfinished community-built top-down RPG demo: a
// 12x8-tile (96x64px) scrolling world of 27 hand-drawn tilemaps across 3
// "worlds", an animated 4-direction walking hero with a sword/charged-spin
// attack, per-tile-quadrant walk flags (wall/water/ice/fall/script), roaming
// enemies, and a small bytecode script interpreter driving map warps and
// dialogue boxes.
//
// -----------------------------------------------------------------------------
//   DATA.DAT / SOUND.DAT - the real SD-card question, resolved
// -----------------------------------------------------------------------------
// Real upstream reads BOTH of its data files off a real SD card at runtime,
// through a third-party FAT library (`GB_Fat sd; sd.init(...); datfile =
// sd.open("DATA.DAT", ...)`), not from PROGMEM - the entire world (sprites,
// tilemaps, scripts, dialogue text) lives outside the sketch. Nothing about
// that mechanism is portable to Vircon32, which has no filesystem at all.
// Resolved differently for each of the two files, after reading
// `create_data.py`/`getData.sh` to establish what each one really is:
//
// * DATA.DAT (7873 bytes) is pure static content, generated build-time by the
//   author's own PHP web level editor (`dev tool/`) and fetched with
//   `getData.sh` - the *content* is the real portable asset, the SD read is
//   just how a 32KB AVR got at 8KB of world data it had no flash room for.
//   Embedded here verbatim, byte-for-byte, as `crpgDat[]` (one plain int per
//   real file byte, exactly like every other ported game's own PROGMEM tables
//   in this project), and every real `datfile.read(dst, addr, len)` call site
//   rewritten to a direct indexed read of that array. This is a pure
//   mechanism swap: not one byte of the real world data is altered, so every
//   map/sprite/script/dialogue string is exactly what a real cartridge with a
//   real SD card would have loaded.
//
//   The rewrite additionally makes upstream's own screenbuffer-as-scratch
//   trick unnecessary: real `loadTilemap()`/`Script::readProg()` read 256/512
//   byte blocks straight into the 504-byte LCD framebuffer and index into it
//   (a genuine 8-byte buffer overrun in the 512-byte cases, harmless only
//   because of what happens to sit after it in AVR RAM). With the whole file
//   already resident, those staging reads collapse into plain array indexing -
//   provably the same bytes, minus the overrun.
//
// * SOUND.DAT (2048 bytes) is NOT portable content in the same sense. It is
//   two 1024-byte tracker songs which real `loadSong()` reads off the SD card
//   and then WRITES INTO THE MCU'S OWN FLASH at runtime
//   (`write_flash_page((const char*)SOUNDBUFFER_OFFSET, ...)`, address
//   231*128 = 29568 - exactly the `upload.maximum_size` in the repo's own
//   `hardware/.../boards.txt`, i.e. the first flash page past the sketch), so
//   that a MODIFIED Gamebuino Sound library can play a pattern set from a
//   hardcoded flash address with no RAM cost. That is a self-programming
//   bootloader hack with no Vircon32 equivalent whatsoever, and it depends on
//   a modified library that is not in the repo at all (`gb.sound.playTrack(0)`
//   does not match the real library's own two-argument signature - the real
//   call is commented out right below it). The whole music path is therefore
//   dropped, matching this project's long-standing one-shot-tone scope limit
//   for every ported game's real tracker music (gameArmageddon.c/gameCopter.c/
//   gameBomber.c precedent). This game makes no other sound call at all, so
//   nothing else was lost - it is silent, exactly as much as upstream is
//   silent without its own modified library.
//
// * EEPROM: `#include <EEPROM.h>` in the real .ino is dead - a project-wide
//   grep across every real source file finds no `EEPROM.read()`/`.write()`
//   call anywhere, and there is no save/progress concept in the game at all.
//   No persistence was invented, matching this project's own gameShipwrek.c/
//   gameStarHonor.c precedent for exactly this situation.
//
// * `dev tool/` (7 PHP scripts) is confirmed to be the author's own web-based
//   sprite/tilemap/script editor - the build-time producer of DATA.DAT, run on
//   sorunome.de and downloaded by `getData.sh`. Not firmware; excluded, per
//   this project's own "don't port desktop/build tooling" precedent.
//   `hardware/gamebuino-community-rpg/avr/boards.txt` (an Arduino board
//   definition) and the byte-identical nested `gamebuino-community-rpg/`
//   duplicate of `src/` are likewise excluded.
//
// -----------------------------------------------------------------------------
//   Two hand-written AVR assembly sprite blitters, reimplemented in C
// -----------------------------------------------------------------------------
// `graphics.cpp`'s `sprite_masked()`/`sprite_xor()` are pure inline AVR asm
// operating directly on the PCD8544 page framebuffer. Both were decoded
// instruction by instruction and reimplemented as plain C against this shim's
// own `gbFrameBuffer[]`, which uses the identical layout (`buf[x + (y/8)*84]`,
// bit `y%8`, LSB = top) - so this is a genuine byte-level reimplementation,
// not a per-pixel approximation:
//   * both take an 8-column sprite and shift each column byte down by `y & 7`,
//     writing the low part into page `(y+8)/8 - 1` and the spill-over into
//     page `(y+8)/8`;
//   * `sprite_xor` XORs the shifted column into the page;
//   * `sprite_masked` takes 16 bytes as <mask><sprite> pairs and computes
//     `dest = (dest & mask) ^ sprite`, with the mask shifted in with 1-fill
//     (the asm's own `sec; rol`) and the sprite with 0-fill;
//   * clipping matches the asm exactly: whole sprite skipped when `y+7 < 0` or
//     `y >= 48`, the upper page skipped when `y < 0`, the lower page skipped
//     when `y >= 40`, and each column skipped when `x < 0 || x >= 84`.
// Written at byte granularity (one framebuffer read/modify/write per column
// per page) rather than calling gbDrawPixel() 64 times per sprite - this
// project's own documented call-overhead lesson (see CLAUDE.md's performance
// pass, and the gamePirates.c per-pixel masking blowup), and it also happens
// to be what the original asm literally does. gbDrawPixel()'s own
// gbGrayBuffer "un-gray" bookkeeping is reproduced at the same granularity so
// the Button-R real-gray mode stays correct (this game never draws GB_GRAY
// itself, so it is a no-op here in practice, but the gamePirates.c regression
// makes it worth doing anyway).
//
// -----------------------------------------------------------------------------
//   The one deliberate behavioural deviation: held vs. edge-triggered buttons
// -----------------------------------------------------------------------------
// Real upstream reads EVERY input through `gb.buttons.pressed(BTN_x)`. In the
// STOCK Gamebuino Classic library that is strictly edge-triggered
// (`Buttons::pressed()` returns `states[button] == 1`, true on exactly the one
// frame a button goes down - confirmed by reading the real utility/Buttons.cpp
// directly, not assumed). Ported literally, that makes this game unplayable
// and its own code self-contradictory:
//   * movement is velocity based with `vx` clamped to exactly 0x100 (= 1px per
//     frame) and a per-frame deceleration of `acceleration + 1`, where
//     acceleration is 255 on land: an edge-only press produces exactly one
//     pixel of movement and then a full stop, and the real water (10) / ice
//     (4) acceleration values would make those surfaces immovable rather than
//     slippery. The entire acceleration/friction system only means anything
//     with continuously-held input.
//   * the sword state machine is explicitly a charge-up: `update_sword_spin()`
//     drops out of the spin the moment `!pressed(BTN_A)`, and
//     `update_sword_spin_do_wait()` counts up while `pressed(BTN_A)` and fires
//     the spin attack on release. With edge semantics `!pressed(A)` is true on
//     every frame after the first, so the charged spin attack is unreachable -
//     dead code the author clearly wrote to be reached.
// Upstream also demonstrably ships against a MODIFIED Gamebuino library (see
// the SOUND.DAT note above - `playTrack(0)` is not the stock signature), and
// that modified library is not in the repo, so stock `pressed()` semantics are
// not actually "what real upstream did" - they are just what the stock library
// would do with upstream's source. Every button read here is therefore
// `crpgBtn()` = `gbHeld(btn, 1)` ("currently down"), which is the only reading
// under which this game's own physics and combat code are coherent. This is
// the single deliberate deviation in the port; everything else below is
// preserved as written.
//
// -----------------------------------------------------------------------------
//   Blocking script interpreter, flattened into a state machine
// -----------------------------------------------------------------------------
// Real `Script::run()`/`dispText()` block: they `delay()`, spin on
// `while(gb.buttons.pressed(BTN_A));` loops, and call `gb.display.update()`
// mid-script, all without ever returning to `loop()`. Flattened here the same
// way gamePetitMonstre.c flattened its own nested blocking combat loops - one
// resumable interpreter (`crpgScriptStep()`) driven once per tick from
// `gameCommunityRpg_update()`, plus a small text sub-state machine. Details:
//   * `SCRIPT_UPDATE_SCREEN` yields exactly one frame (real hardware only paid
//     an SPI transfer). This is what makes the one real animated script in the
//     data - map 13/14's `INC PLAYER_X; FOCUS_CAM; UPDATE_SCREEN; JUMP_IF
//     (PLAYER_X < 32)` walk-in loop - actually animate rather than teleport.
//   * `SCRIPT_TEXT` runs one character per 2 ticks (= real `delay(100)` at the
//     20fps default), fast-forwarding while Button A is held once it has been
//     released at least once, which is exactly what upstream's own `j` flag
//     was written to express.
//   * `SCRIPT_FADE_TO_WHITE`/`FADE_FROM_WHITE` are no-ops. They drive the real
//     PCD8544 contrast register (`setScreenContrast_unsafe()`), a physical LCD
//     property with no framebuffer equivalent at all here - the same class of
//     real-hardware-only call this project already drops elsewhere (backlight,
//     battery display). Both only ever bracket a map warp, so the visible
//     result is a hard cut instead of a ~300ms fade.
//   * a script's own true/false result reaches its interrupted caller through
//     `crpgScriptCtx` + `crpgScriptFinish()`. One consequence is documented as
//     a deviation: when a script triggered by *walking into* a script tile
//     returns true, upstream applies `x += vx` and then still runs the whole
//     y-movement block in that same frame; here the deferred completion
//     applies the pending axis move and ends the frame, losing one frame of
//     the other axis. No shipped script hits this (the one true-returning
//     script sits on a manual/Button-A tile).
//   * a start-script on map load (`header & 0x02`) is queued and run at the
//     next top-level tick rather than nested inside `loadTilemap()`. No map in
//     the shipped DATA.DAT sets that bit (verified by decoding all 27 map
//     headers), so this path is untested-by-construction.
//
// A real upstream hang, NOT reproduced: `dispText()`'s three
// `while(gb.buttons.pressed(BTN_A));` / `while(!gb.buttons.pressed(BTN_A));`
// spin loops never call `gb.update()`, so the button state they poll is frozen
// for the whole loop - on stock library semantics at least one of the three
// can never terminate, whichever way A happens to be latched on entry. Ported
// as the obviously-intended live three-stage "wait for release, wait for
// press, wait for release" gate, per this project's own established "don't
// preserve a real infinite loop" exception (gameUnderTheTower.c,
// gamePetitMonstre.c).
//
// -----------------------------------------------------------------------------
//   Real upstream quirks preserved deliberately
// -----------------------------------------------------------------------------
// * `Player::update_idle()`'s direction formula looks inverted on its first
//   line (`direction = (1+x_temp)*(x_temp!=0)` maps "right" to 2 = LEFT) and
//   is then silently corrected by the second line's `|| direction == 0`
//   clause. Traced through all six input cases and reproduced exactly rather
//   than "cleaned up" - it does produce the right answer, including the
//   diagonal-prefers-vertical case.
// * The wall bounce (`WALL_X()` = `x += vx; vx = -vx;` immediately before the
//   shared `x += vx;` below the switch) nets out to "position unchanged,
//   velocity reflected". Preserved as written.
// * `SCRIPT_JUMP`/`JUMP_IF`/`JUMP_IFNOT`/`CALL` read only ONE byte into the
//   4-byte cursor (`readProg((byte*)&cursor, 1)` on a little-endian
//   `uint32_t`), so a jump can only ever move within the current 256-byte
//   page - reproduced exactly as `cursor = cursor - (cursor & 0xFF) + byte`.
//   This is deliberate upstream (the dev tool still writes a full 4-byte
//   field, which the interpreter skips with `cursor += 4`), and the one real
//   jump in the shipped data lands correctly through it (target field
//   0x00001EB3, low byte 0xB3, cursor 7868 -> 7859).
// * `SCRIPT_ADD_ENEMY` does NOT consume its own x/y operands when the enemy
//   table is full, desynchronising the instruction stream. No shipped script
//   uses the opcode at all; preserved.
// * `Script::condition()` has no `return` for any opcode other than
//   `SCRIPT_LT` (undefined behaviour upstream); returns false here.
// * `Enemy::update()`'s `if (!counter--)` relies on real `byte` wraparound;
//   reproduced with an explicit `& 0xFF`.
// * Both `getWalkInfo_x()`/`getWalkInfo_y()` bounds-check only the axis being
//   moved along, never the other one, and `getTileAt()` divides signed
//   coordinates - preserved, with a clamp inside `crpgGetTileAt()` that is a
//   provable no-op for every reachable coordinate but keeps an out-of-range
//   index from reading an unrelated global on this platform.
// * The dialogue text is upstream's own literal "lorem ipsum" placeholder.
//   Kept verbatim - it is what the shipped world data contains.
// * Real upstream never calls `gb.titleScreen()`, so this port has no title
//   screen either; play starts immediately (gameMyRpg.c precedent). The camera
//   likewise starts at (0,0) rather than centred, because real `setup()` never
//   calls `focusCam()`.
//
// -----------------------------------------------------------------------------
//   Platform-forced bounds (upstream would loop forever or read out of range)
// -----------------------------------------------------------------------------
// * `loadTilemap()`'s animated-sprite slot search is `for (num = 30; num >= 0;
//   num -= 2)` with `num` declared `uint8_t` - it wraps to 254 and indexes far
//   past its own 32-entry table when a map needs more than 16 animated tiles.
//   Written as a genuine signed loop here with an explicit "no slot found ->
//   tile 0" fallback.
// * The tilemap-LUT scan and the script-LUT scan are both `while(true)` loops
//   with no not-found exit; both are bounded here.
// * The interpreter has a 4096-opcode-per-tick guard, and an opcode fetch past
//   the end of the data ends the script cleanly (there are two degenerate
//   script-table entries in the shipped data pointing at offset 7873, i.e. one
//   past EOF).
//
// Every real `gb.x.y(...)` call site was mechanically rewritten to a plain
// `gbY(...)` call (see gamePong.c's own header comment for why - this dialect
// has no classes/methods). Upstream's `Player`/`Enemy`/`Script` C++ classes
// were flattened into plain globals plus free functions, and `Player`'s own
// PROGMEM function-pointer status table into an if/else dispatch (a flash-size
// optimisation on AVR, not behaviour). `Script`'s `byte* ptr` variable-pointer
// trick - which aliases either a script variable, `currentMap`, `currentWorld`
// or the HIGH BYTE of the player's 16.8 fixed-point x/y - became an explicit
// selector (`crpgVarSel`/`crpgVarIdx`) plus `crpgScriptVarRead()`/
// `crpgScriptVarWrite()`, since this dialect has no byte pointers at all.
// Player x/y stay genuine `int16_t`-ranged values with explicit
// `crpgWrap16()`/`crpgHighByte()`/`crpgSetHighByte()` helpers, so the real
// floor-division high-byte semantics (and the script's byte-granular writes to
// it) survive this dialect's always-32-bit, never-narrowing `int`.

