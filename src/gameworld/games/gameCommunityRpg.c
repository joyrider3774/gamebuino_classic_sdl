int crpgCalcSwordX( bool cond )
{
    int near = 8;
    if( cond ) near = 6;

    int v = crpgPX();
    if( crpgPlayerDirection == 0 ) v = v + near;
    if( crpgPlayerDirection == 2 ) v = v - near;
    if( cond )
    {
        if( crpgPlayerDirection == 1 ) v = v + 6;
        if( crpgPlayerDirection == 3 ) v = v - 6;
    }
    return v;
}

int crpgCalcSwordY( bool cond )
{
    int near = 8;
    if( cond ) near = 6;

    int v = crpgPY();
    if( crpgPlayerDirection == 3 ) v = v + near;
    if( crpgPlayerDirection == 1 ) v = v - near;
    if( cond )
    {
        if( crpgPlayerDirection == 0 ) v = v + 6;
        if( crpgPlayerDirection == 2 ) v = v - 6;
    }
    return v;
}

int crpgUpdateIdle()
{
    if( crpgBtn( BTN_A ) )
    {
        crpgMoveX = 0;
        if( crpgPlayerDirection == 0 ) crpgMoveX = 1;
        if( crpgPlayerDirection == 2 ) crpgMoveX = -1;
        crpgMoveY = 0;
        if( crpgPlayerDirection == 3 ) crpgMoveY = 1;
        if( crpgPlayerDirection == 1 ) crpgMoveY = -1;

        int w = crpgGetWalkInfo( crpgPX() + 2, crpgPY() + 4, 4, 4, crpgMoveX, crpgMoveY );
        if( w == CRPG_FLAG_TILE_MANUAL_SCRIPT )
        {
            if( crpgMoveX > 0 ) crpgMoveX = 4;
            if( crpgMoveY > 0 ) crpgMoveY = 4;
            crpgScriptLoadInTilemap( ( ( crpgPX() + 2 + crpgMoveX ) / 8 )
                                   + ( ( ( crpgPY() + 4 + crpgMoveY ) / 8 ) * CRPG_TILEMAP_WIDTH ) );
            crpgScriptStart( CRPG_SCTX_IDLE_A );
            return CRPG_RES_SCRIPT;
        }

        crpgPlayerCounter = 0;
        crpgPlayerAnimation = 2;
        crpgPlayerStatus = CRPG_ST_SWORD_SPIN;
        return CRPG_RES_CONTINUE;
    }

    // only idle updates direction & animation
    if( crpgMoveX != 0 || crpgMoveY != 0 )
    {
        crpgPlayerAnimation = ( crpgMillis() / CRPG_ANIMATION_FREQUENCY ) % 2;

        // real upstream's own two-line formula, reproduced exactly - the
        // seemingly-inverted first line is corrected by the second's
        // `|| direction == 0` clause (see this file's own header comment)
        if( crpgMoveX != 0 ) crpgPlayerDirection = 1 + crpgMoveX;
        else crpgPlayerDirection = 0;

        if( crpgMoveY != 0 || crpgPlayerDirection == 0 )
          crpgPlayerDirection = 2 + crpgMoveY;
        else
          crpgPlayerDirection = 0;
    }
    return CRPG_RES_CONTINUE;
}

int crpgUpdateFallWait()
{
    if( crpgMoveY != 1 )
    {
        crpgPlayerStatus = CRPG_ST_IDLE;
        return CRPG_RES_CONTINUE;
    }
    int old = crpgPlayerCounter;
    crpgPlayerCounter = old + 1;
    if( old > 10 ) crpgPlayerStatus = CRPG_ST_FALL;

    crpgMoveX = 0;
    crpgMoveY = 0;
    return 1;
}

int crpgUpdateFall()
{
    crpgPlayerY = crpgWrap16( crpgPlayerY + 0x100 );

    if( crpgPY() > ( CRPG_TILEMAP_HEIGHT * 8 ) - 8 )
    {
        crpgCurrentMap = ( crpgCurrentMap + CRPG_DATFILE_TILEMAPS_WIDTH ) & 0xFF;
        crpgPlayerY = crpgWrap16( -4 * 0x100 );
        return 0;
    }

    if( crpgGetWalkInfoY( crpgPX() + 2, crpgPY(), 4, 4, 1 ) <= CRPG_FLAG_TILE_WALKABLE )
      if( crpgGetWalkInfoY( crpgPX() + 2, crpgPY() + 4, 4, 4, 1 ) <= CRPG_FLAG_TILE_WALKABLE )
        crpgPlayerStatus = CRPG_ST_IDLE;

    crpgFocusCam();
    return 1;
}

int crpgUpdateSwordSpin()
{
    if( !crpgBtn( BTN_A ) ) crpgPlayerStatus = CRPG_ST_SWORD;

    crpgPlayerCounter = crpgPlayerCounter + 1;
    if( crpgPlayerCounter >= 20 )
    {
        crpgPlayerCounter = 0;
        if( crpgPlayerStatus == CRPG_ST_SWORD_SPIN )
          crpgPlayerStatus = CRPG_ST_SWORD_SPIN_DO_WAIT;
        else
        {
            crpgPlayerAnimation = 0;
            crpgPlayerStatus = CRPG_ST_IDLE;
        }
    }

    crpgMoveX = 0;
    crpgMoveY = 0;
    return CRPG_RES_CONTINUE;
}

int crpgUpdateSwordSpinDoWait()
{
    if( crpgBtn( BTN_A ) )
    {
        crpgPlayerCounter = crpgPlayerCounter + 1;
        if( crpgPlayerCounter >= 12 + 6 ) crpgPlayerCounter = 12;
    }
    else
    {
        if( crpgPlayerCounter >= 12 )
        {
            crpgPlayerCounter = 0;
            crpgPlayerStatus = CRPG_ST_SWORD_SPIN_DO;
        }
        else
        {
            crpgPlayerCounter = 0;
            crpgPlayerAnimation = 0;
            crpgPlayerStatus = CRPG_ST_IDLE;
        }
    }
    // real upstream deliberately has no NOMOVE() here - the player can still
    // walk while holding a charged spin
    return CRPG_RES_CONTINUE;
}

int crpgUpdateSwordSpinDo()
{
    int old = crpgPlayerCounter;
    crpgPlayerCounter = old + 1;
    if( ( old % 6 ) == 0 )
    {
        crpgPlayerDirection = crpgPlayerDirection + 1;
        crpgPlayerDirection = crpgPlayerDirection % 4;
    }
    if( crpgPlayerCounter >= 4 * 6 )
    {
        crpgPlayerAnimation = 0;
        crpgPlayerStatus = CRPG_ST_IDLE;
    }

    crpgMoveX = 0;
    crpgMoveY = 0;
    return CRPG_RES_CONTINUE;
}

// Real upstream dispatches these through a PROGMEM function-pointer table
// (a flash-size optimisation on AVR, not behaviour)
int crpgPlayerStatusDispatch()
{
    if( crpgPlayerStatus == CRPG_ST_IDLE ) return crpgUpdateIdle();
    if( crpgPlayerStatus == CRPG_ST_FALL_WAIT ) return crpgUpdateFallWait();
    if( crpgPlayerStatus == CRPG_ST_FALL ) return crpgUpdateFall();
    if( crpgPlayerStatus == CRPG_ST_SWORD ) return crpgUpdateSwordSpin(); // real update_sword() forwards here
    if( crpgPlayerStatus == CRPG_ST_SWORD_SPIN ) return crpgUpdateSwordSpin();
    if( crpgPlayerStatus == CRPG_ST_SWORD_SPIN_DO_WAIT ) return crpgUpdateSwordSpinDoWait();
    return crpgUpdateSwordSpinDo();
}

// Real Player::update(). Returns 1 = carry on and draw, 0 = the player left
// the tilemap, 2 = a script just started and owns the coming frames.
int crpgPlayerUpdate()
{
    crpgMoveX = 0;
    if( crpgBtn( BTN_LEFT ) ) crpgMoveX = crpgMoveX - 1;
    if( crpgBtn( BTN_RIGHT ) ) crpgMoveX = crpgMoveX + 1;
    crpgMoveY = 0;
    if( crpgBtn( BTN_UP ) ) crpgMoveY = crpgMoveY - 1;
    if( crpgBtn( BTN_DOWN ) ) crpgMoveY = crpgMoveY + 1;

    int res = crpgPlayerStatusDispatch();
    if( res == CRPG_RES_SCRIPT ) return 2;
    if( res != CRPG_RES_CONTINUE )
    {
        if( res != 0 ) return 1;
        return 0;
    }

    // ---- x axis ----
    if( crpgMoveX != 0 )
    {
        crpgPlayerVx = crpgPlayerVx + crpgMoveX * crpgPlayerAcceleration;
        crpgPlayerVx = crpgPlayerVx + crpgMoveX; // real upstream wants one more
        if( crpgPlayerVx > 0x100 ) crpgPlayerVx = 0x100;
        if( crpgPlayerVx < -0x100 ) crpgPlayerVx = -0x100;
    }

    bool decelX = false;
    if( crpgMoveX == 0 ) decelX = true;
    if( crpgMoveX > 0 && crpgPlayerVx < 0 ) decelX = true;
    if( crpgMoveX < 0 && crpgPlayerVx > 0 ) decelX = true;
    if( decelX )
    {
        if( crpgPlayerVx > 0 )
        {
            crpgPlayerVx = crpgPlayerVx - crpgPlayerAcceleration - 1;
            if( crpgPlayerVx < 0 ) crpgPlayerVx = 0;
        }
        else if( crpgPlayerVx < 0 )
        {
            crpgPlayerVx = crpgPlayerVx + crpgPlayerAcceleration + 1;
            if( crpgPlayerVx > 0 ) crpgPlayerVx = 0;
        }
    }

    if( crpgPlayerVx != 0 )
    {
        if( crpgPlayerVx > 0 ) crpgMoveX = 1;
        else crpgMoveX = -1;

        int w = crpgGetWalkInfoX( crpgPX() + 2, crpgPY() + 4, 4, 4, crpgMoveX );

        if( w == CRPG_FLAG_TILE_WALKABLE ) crpgPlayerAcceleration = 0xFF;
        else if( w == CRPG_FLAG_TILE_WATER ) crpgPlayerAcceleration = 10;
        else if( w == CRPG_FLAG_TILE_ICE ) crpgPlayerAcceleration = 4;
        else if( w == CRPG_FLAG_TILE_SCREENEND )
        {
            if( crpgMoveX < 0 )
            {
                crpgCurrentMap = ( crpgCurrentMap - 1 ) & 0xFF;
                crpgPlayerX = crpgWrap16( ( ( CRPG_TILEMAP_WIDTH * 8 ) - 8 + 2 ) * 0x100 );
            }
            else
            {
                crpgCurrentMap = ( crpgCurrentMap + 1 ) & 0xFF;
                crpgPlayerX = crpgWrap16( -2 * 0x100 );
            }
            return 0;
        }
        else if( w == CRPG_FLAG_TILE_SCRIPT )
        {
            if( crpgMoveX > 0 ) crpgMoveX = 4;
            crpgScriptLoadInTilemap( ( ( crpgPX() + 2 + crpgMoveX ) / 8 )
                                   + ( ( crpgPY() + 4 ) / 8 ) * CRPG_TILEMAP_WIDTH );
            crpgScriptStart( CRPG_SCTX_MOVE_X );
            return 2;
        }
        else
        {
            // a wall: real WALL_X() plus the shared `x += vx` below nets out
            // to "position unchanged, velocity reflected"
            crpgPlayerX = crpgWrap16( crpgPlayerX + crpgPlayerVx );
            crpgPlayerVx = -crpgPlayerVx;
        }

        crpgPlayerX = crpgWrap16( crpgPlayerX + crpgPlayerVx );
    }

    // ---- y axis ----
    if( crpgMoveY != 0 )
    {
        crpgPlayerVy = crpgPlayerVy + crpgMoveY * crpgPlayerAcceleration;
        crpgPlayerVy = crpgPlayerVy + crpgMoveY;
        if( crpgPlayerVy > 0x100 ) crpgPlayerVy = 0x100;
        if( crpgPlayerVy < -0x100 ) crpgPlayerVy = -0x100;
    }

    bool decelY = false;
    if( crpgMoveY == 0 ) decelY = true;
    if( crpgMoveY > 0 && crpgPlayerVy < 0 ) decelY = true;
    if( crpgMoveY < 0 && crpgPlayerVy > 0 ) decelY = true;
    if( decelY )
    {
        if( crpgPlayerVy > 0 )
        {
            crpgPlayerVy = crpgPlayerVy - crpgPlayerAcceleration - 1;
            if( crpgPlayerVy < 0 ) crpgPlayerVy = 0;
        }
        else if( crpgPlayerVy < 0 )
        {
            crpgPlayerVy = crpgPlayerVy + crpgPlayerAcceleration + 1;
            if( crpgPlayerVy > 0 ) crpgPlayerVy = 0;
        }
    }

    if( crpgPlayerVy != 0 )
    {
        if( crpgPlayerVy > 0 ) crpgMoveY = 1;
        else crpgMoveY = -1;

        int w = crpgGetWalkInfoY( crpgPX() + 2, crpgPY() + 4, 4, 4, crpgMoveY );

        if( w == CRPG_FLAG_TILE_WALKABLE ) crpgPlayerAcceleration = 0xFF;
        else if( w == CRPG_FLAG_TILE_WATER ) crpgPlayerAcceleration = 10;
        else if( w == CRPG_FLAG_TILE_ICE ) crpgPlayerAcceleration = 4;
        else if( w == CRPG_FLAG_TILE_SCREENEND )
        {
            if( crpgMoveY < 0 )
            {
                crpgCurrentMap = ( crpgCurrentMap - CRPG_DATFILE_TILEMAPS_WIDTH ) & 0xFF;
                crpgPlayerY = crpgWrap16( ( ( CRPG_TILEMAP_HEIGHT * 8 ) - 8 ) * 0x100 );
            }
            else
            {
                crpgCurrentMap = ( crpgCurrentMap + CRPG_DATFILE_TILEMAPS_WIDTH ) & 0xFF;
                crpgPlayerY = crpgWrap16( -4 * 0x100 );
            }
            return 0;
        }
        else if( w == CRPG_FLAG_TILE_FALL )
        {
            if( crpgPlayerStatus == CRPG_ST_IDLE )
            {
                crpgPlayerCounter = 0;
                crpgPlayerStatus = CRPG_ST_FALL_WAIT;
            }
            crpgPlayerY = crpgWrap16( crpgPlayerY + crpgPlayerVy );
            crpgPlayerVy = -crpgPlayerVy;
        }
        else if( w == CRPG_FLAG_TILE_SCRIPT )
        {
            if( crpgMoveY > 0 ) crpgMoveY = 4;
            crpgScriptLoadInTilemap( ( ( crpgPX() + 2 ) / 8 )
                                   + ( ( ( crpgPY() + 4 + crpgMoveY ) / 8 ) * CRPG_TILEMAP_WIDTH ) );
            crpgScriptStart( CRPG_SCTX_MOVE_Y );
            return 2;
        }
        else
        {
            crpgPlayerY = crpgWrap16( crpgPlayerY + crpgPlayerVy );
            crpgPlayerVy = -crpgPlayerVy;
        }

        crpgPlayerY = crpgWrap16( crpgPlayerY + crpgPlayerVy );
    }

    crpgFocusCam();
    return 1;
}

void crpgPlayerDraw()
{
    int dirBase = crpgPlayerDirection * 24 * 2;

    if( crpgPlayerStatus == CRPG_ST_SWORD || crpgPlayerStatus == CRPG_ST_SWORD_SPIN )
    {
        bool cond = ( crpgPlayerCounter < 5 );
        int off = dirBase;
        if( cond ) off = off + 16 * 2;
        crpgSpriteMasked( crpgCharsetSword, off, crpgCalcSwordX( cond ), crpgCalcSwordY( cond ) );
    }
    else if( crpgPlayerStatus == CRPG_ST_SWORD_SPIN_DO_WAIT )
    {
        int off = dirBase;
        if( crpgPlayerCounter >= 12 )
          if( ( crpgPlayerCounter % 6 ) >= 3 ) off = off + 16;

        int sx = crpgPX();
        if( crpgPlayerDirection == 0 ) sx = sx + 8;
        if( crpgPlayerDirection == 2 ) sx = sx - 8;
        int sy = crpgPY();
        if( crpgPlayerDirection == 3 ) sy = sy + 8;
        if( crpgPlayerDirection == 1 ) sy = sy - 8;

        crpgSpriteMasked( crpgCharsetSword, off, sx, sy );
    }
    else if( crpgPlayerStatus == CRPG_ST_SWORD_SPIN_DO )
    {
        bool cond = ( ( crpgPlayerCounter % 6 ) < 3 );
        int off = dirBase;
        if( cond ) off = off + 16 * 2;
        crpgSpriteMasked( crpgCharsetSword, off, crpgCalcSwordX( cond ), crpgCalcSwordY( cond ) );
    }

    crpgSpriteMasked( crpgCharsetPlayer, dirBase + crpgPlayerAnimation * 8 * 2,
                      crpgPX(), crpgPY() );
}

// Real drawScreen()
void crpgDrawScreen()
{
    gbClear();
    crpgDrawTilemap();
    crpgPlayerDraw();

    int i;
    for( i = 0; i < CRPG_MAX_NUM_ENEMIES; i++ )
      if( crpgEnemyActive[ i ] != 0 )
        crpgEnemyDraw( i );
}

