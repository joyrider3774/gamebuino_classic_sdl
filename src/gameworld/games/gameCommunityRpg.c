// Real loadTilemap(): resolve the map address through the per-world LUT, then
// build the 32-slot tileset by walking every tile of the map and importing
// each distinct sprite once - static sprites packed from the front of the
// slot table, animated pairs from the back.
void crpgLoadTilemap( int num )
{
    int i;
    for( i = 0; i < CRPG_MAX_NUM_ENEMIES; i++ )
      crpgEnemyActive[ i ] = 0;

    crpgFirstAnimatedSprite = CRPG_TILEMAPS_SPRITESPACE;

    crpgMapAddress = crpgRead32( CRPG_DATFILE_START_TILEMAPLUT + crpgCurrentWorld * 4 );

    // Real upstream scans this LUT in 256-byte SD reads with a 255-byte
    // re-base; with the whole file resident that is exactly a linear scan of
    // 5-byte entries. Bounded here - upstream's own loop has no not-found
    // exit at all.
    int p = crpgMapAddress;
    bool found = false;
    int guard = 0;
    while( guard < 512 )
    {
        guard = guard + 1;
        if( p < 0 ) break;
        if( p + 4 >= CRPG_DAT_SIZE ) break;
        if( crpgDatByte( p ) == num )
        {
            crpgMapAddress = crpgRead32( p + 1 );
            found = true;
            break;
        }
        p = p + 5;
    }
    if( !found ) return;
    if( crpgMapAddress < 0 ) return;
    if( crpgMapAddress + CRPG_DATFILE_TILEMAP_SIZE > CRPG_DAT_SIZE ) return;

    int header = crpgDatByte( crpgMapAddress );

    for( i = 0; i < CRPG_TILEMAPS_SPRITESPACE; i++ )
      crpgHaveSprite[ i ] = 0xFFFF;

    for( i = 0; i < CRPG_TILEMAP_SIZE; i++ )
    {
        int tile = crpgRead16( crpgMapAddress + CRPG_DATFILE_TILEMAPS_HEADER_SIZE + i * 2 );
        bool placed = false;
        int slot, src, k;

        if( tile >= CRPG_SPRITES_FIRST_ANIMATED )
        {
            // Real upstream's own `for (num = SPRITESPACE-2; num >= 0; num -= 2)`
            // with num declared uint8_t, which wraps to 254 and reads far past
            // the table when a map needs more than 16 animated tiles - a
            // genuine signed loop here, with an explicit fallback below.
            for( slot = CRPG_TILEMAPS_SPRITESPACE - 2; slot >= 0; slot = slot - 2 )
            {
                if( crpgHaveSprite[ slot ] == tile )
                {
                    crpgTilemap[ i ] = slot;
                    placed = true;
                    break;
                }
                if( crpgHaveSprite[ slot ] == 0xFFFF )
                {
                    crpgHaveSprite[ slot ] = tile;
                    src = ( ( tile - CRPG_SPRITES_FIRST_ANIMATED ) * 17 )
                        + CRPG_DATFILE_START_SPRITES
                        + ( CRPG_SPRITES_FIRST_ANIMATED * 9 );
                    crpgWalksprites[ slot ] = crpgDatByte( src );
                    for( k = 0; k < 16; k++ )
                      crpgTileset[ slot * 8 + k ] = crpgDatByte( src + 1 + k );
                    crpgTilemap[ i ] = slot;
                    crpgFirstAnimatedSprite = slot;
                    placed = true;
                    break;
                }
            }
        }
        else
        {
            for( slot = 0; slot < CRPG_TILEMAPS_SPRITESPACE; slot++ )
            {
                if( crpgHaveSprite[ slot ] == tile )
                {
                    crpgTilemap[ i ] = slot;
                    placed = true;
                    break;
                }
                if( crpgHaveSprite[ slot ] == 0xFFFF )
                {
                    crpgHaveSprite[ slot ] = tile;
                    src = ( tile * 9 ) + CRPG_DATFILE_START_SPRITES;
                    crpgWalksprites[ slot ] = crpgDatByte( src );
                    for( k = 0; k < 8; k++ )
                      crpgTileset[ slot * 8 + k ] = crpgDatByte( src + 1 + k );
                    crpgTilemap[ i ] = slot;
                    placed = true;
                    break;
                }
            }
        }

        if( !placed ) crpgTilemap[ i ] = 0;
    }

    // Real upstream runs a map's start script inline, from a second Script
    // instance, right here. Queued instead - see this file's own header
    // comment. No map in the shipped data sets this bit.
    if( ( header & 0x02 ) != 0 )
      crpgPendingStartCursor = crpgRead32( crpgMapAddress + CRPG_DATFILE_TILEMAP_SIZE );
}

