// Real getTileAt(). The clamp is a platform-forced guard only: every
// reachable coordinate is already in range because getWalkInfo_x/_y reject
// off-map moves before ever calling in here (see this file's own header
// comment).
int crpgGetTileAt( int x, int y )
{
    int idx = ( x / 8 ) + ( y / 8 ) * CRPG_TILEMAP_WIDTH;
    if( idx < 0 ) idx = 0;
    if( idx >= CRPG_TILEMAP_SIZE ) idx = CRPG_TILEMAP_SIZE - 1;
    return crpgTilemap[ idx ];
}

// Real getFlagAt(): the low nibble of a tile's walk byte holds one bit per
// 4x4 quadrant, the high nibble holds (flag - 2).
int crpgGetFlagAt( int x, int y )
{
    int tmp = crpgWalksprites[ crpgGetTileAt( x, y ) ] & 0xFF;

    int bx = 0;
    if( ( x % 8 ) < 4 ) bx = 1;
    int by = 0;
    if( ( y % 8 ) < 4 ) by = 1;

    int bit = ( tmp >> ( bx + 2 * by ) ) & 0x01;
    return 1 + bit * ( ( tmp >> 4 ) + 1 );
}

int crpgGetWalkInfoX( int x, int y, int w, int h, int dx )
{
    if( dx == 0 ) return CRPG_FLAG_TILE_WALKABLE;

    int tmp;
    w = w - 1;
    h = h - 1;

    x = x + dx;
    if( dx > 0 )
    {
        if( x + w >= CRPG_TILEMAP_WIDTH * 8 ) return CRPG_FLAG_TILE_SCREENEND;
        tmp = crpgGetFlagAt( x + w, y );
        if( tmp <= CRPG_FLAG_TILE_WALKABLE ) return crpgGetFlagAt( x + w, y + h );
        return tmp;
    }
    if( x < 0 ) return CRPG_FLAG_TILE_SCREENEND;
    tmp = crpgGetFlagAt( x, y );
    if( tmp <= CRPG_FLAG_TILE_WALKABLE ) return crpgGetFlagAt( x, y + h );
    return tmp;
}

int crpgGetWalkInfoY( int x, int y, int w, int h, int dy )
{
    if( dy == 0 ) return CRPG_FLAG_TILE_WALKABLE;

    int tmp;
    w = w - 1;
    h = h - 1;

    y = y + dy;
    if( dy > 0 )
    {
        if( y + h >= CRPG_TILEMAP_HEIGHT * 8 ) return CRPG_FLAG_TILE_SCREENEND;
        tmp = crpgGetFlagAt( x, y + h );
        if( tmp <= CRPG_FLAG_TILE_WALKABLE ) return crpgGetFlagAt( x + w, y + h );
        return tmp;
    }
    if( y < 0 ) return CRPG_FLAG_TILE_SCREENEND;
    tmp = crpgGetFlagAt( x, y );
    if( tmp <= CRPG_FLAG_TILE_WALKABLE ) return crpgGetFlagAt( x + w, y );
    return tmp;
}

int crpgGetWalkInfo( int x, int y, int w, int h, int dx, int dy )
{
    if( dx != 0 ) return crpgGetWalkInfoX( x, y, w, h, dx );
    return crpgGetWalkInfoY( x, y, w, h, dy );
}

