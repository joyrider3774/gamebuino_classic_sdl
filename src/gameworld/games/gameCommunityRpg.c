// One framebuffer page-byte read/modify/write: dest = (dest & mask) ^ val,
// exactly what both blitters' inner loops do. `touched` is the set of bits
// this write is authoritative over, so the real-gray bit plane can be
// un-grayed at the same granularity gbDrawPixel() would (see this file's own
// header comment).
void crpgBlitCol( int idx, int mask, int val )
{
    int old = gbFrameBuffer[ idx ] & 0xFF;
    int nw = ( old & mask ) ^ val;
    gbFrameBuffer[ idx ] = nw;

    if( gbRealGrayColor && gbAnyGrayDrawn )
    {
        int touched = ( 0xFF - mask ) | val;
        gbGrayBuffer[ idx ] = gbGrayBuffer[ idx ] & ( 0xFF - touched );
    }
}

// Real sprite_masked(): 16 bytes of <mask><sprite> column pairs.
// Mask is AND'd (1 = keep whatever is underneath), sprite is XOR'd on top.
void crpgSpriteMasked( int* data, int off, int xx, int yy )
{
    int x = xx - crpgCamX;
    int y = yy - crpgCamY;

    if( y + 7 < 0 ) return;
    if( y >= LCDHEIGHT ) return;

    int shift = ( y + 8 ) & 7;
    int pageLo = ( ( y + 8 ) & 0xF8 ) / 8;
    int pageHi = pageLo - 1;
    bool doHi = ( y >= 0 );
    bool doLo = ( y < 40 );

    int col;
    for( col = 0; col < 8; col++ )
    {
        int px = x + col;
        if( px < 0 ) continue;
        if( px >= LCDWIDTH ) continue;

        int m = data[ off + col * 2 ] & 0xFF;
        int s = data[ off + col * 2 + 1 ] & 0xFF;

        if( shift == 0 )
        {
            // the asm's own aligned fast path - one page only
            if( doHi ) crpgBlitCol( px + pageHi * LCDWIDTH, m, s );
            continue;
        }

        // mask shifts in 1s from the right (the asm's `sec; rol`), sprite 0s
        int mHi = ( ( m << shift ) | ( ( 1 << shift ) - 1 ) ) & 0xFF;
        int sHi = ( s << shift ) & 0xFF;
        int mLo = ( ( m >> ( 8 - shift ) ) | ( 0xFF << shift ) ) & 0xFF;
        int sLo = ( s >> ( 8 - shift ) ) & 0xFF;

        if( doHi ) crpgBlitCol( px + pageHi * LCDWIDTH, mHi, sHi );
        if( doLo ) crpgBlitCol( px + pageLo * LCDWIDTH, mLo, sLo );
    }
}

// Real sprite_xor(): 8 plain column bytes, XOR'd into the framebuffer
void crpgSpriteXor( int* data, int off, int xx, int yy )
{
    int x = xx - crpgCamX;
    int y = yy - crpgCamY;

    if( y + 7 < 0 ) return;
    if( y >= LCDHEIGHT ) return;

    int shift = ( y + 8 ) & 7;
    int pageLo = ( ( y + 8 ) & 0xF8 ) / 8;
    int pageHi = pageLo - 1;
    bool doHi = ( y >= 0 );
    bool doLo = ( y < 40 );

    int col;
    for( col = 0; col < 8; col++ )
    {
        int px = x + col;
        if( px < 0 ) continue;
        if( px >= LCDWIDTH ) continue;

        int s = data[ off + col ] & 0xFF;

        if( shift == 0 )
        {
            if( doHi ) crpgBlitCol( px + pageHi * LCDWIDTH, 0xFF, s );
            continue;
        }

        int sHi = ( s << shift ) & 0xFF;
        int sLo = ( s >> ( 8 - shift ) ) & 0xFF;

        if( doHi ) crpgBlitCol( px + pageHi * LCDWIDTH, 0xFF, sHi );
        if( doLo ) crpgBlitCol( px + pageLo * LCDWIDTH, 0xFF, sLo );
    }
}

// Real drawTilemap(). Animated tiles occupy consecutive slot pairs, so the
// second frame is simply slot+1 - real upstream's own
// `tile_num += (tile_num >= firstAnimatedSprite)*millis()/ANIMATION_FREQUENCY%2`
// (which parses as `(((cond)*millis())/500)%2`).
void crpgDrawTilemap()
{
    int startDdx = ( -crpgCamX ) / 8;
    int startDdy = ( -crpgCamY ) / 8;
    int maxDdx = ( LCDWIDTH + 8 - 1 + crpgCamX ) / 8;
    int maxDdy = ( LCDHEIGHT + 8 - 1 + crpgCamY ) / 8;

    if( CRPG_TILEMAP_WIDTH < maxDdx ) maxDdx = CRPG_TILEMAP_WIDTH;
    if( CRPG_TILEMAP_HEIGHT < maxDdy ) maxDdy = CRPG_TILEMAP_HEIGHT;
    if( startDdx < 0 ) startDdx = 0;
    if( startDdy < 0 ) startDdy = 0;

    int animPhase = ( crpgMillis() / CRPG_ANIMATION_FREQUENCY ) % 2;

    int ddx, ddy;
    for( ddy = startDdy; ddy < maxDdy; ddy++ )
      for( ddx = startDdx; ddx < maxDdx; ddx++ )
      {
        int tileNum = crpgTilemap[ ddy * CRPG_TILEMAP_WIDTH + ddx ];
        if( tileNum >= crpgFirstAnimatedSprite ) tileNum = tileNum + animPhase;
        // A static tile that happens to land on the last slot while the map
        // also has animated tiles would step one slot past the 32-slot
        // tileset here (real upstream reads 8 bytes off the end of its own
        // byte[8*32] the same way). Decoding all 27 shipped maps shows it
        // never actually happens; bounded anyway rather than reading an
        // unrelated global on this platform.
        if( tileNum > CRPG_TILEMAPS_SPRITESPACE - 1 ) tileNum = CRPG_TILEMAPS_SPRITESPACE - 1;
        crpgSpriteXor( crpgTileset, tileNum * CRPG_TILE_HEIGHT, ddx * 8, ddy * 8 );
      }
}

