// One real step-back entry in the undo ring buffer: `pos` is the vram
// index the player stood on before the push, `offset` is the direction
// (one of SOKO_OFFSET_*) that push moved things in.
typedef struct{
    int pos;
    int offset;
} SokoUndoEntry;
SokoUndoEntry sokoUndoRingbuffer[SOKO_UNDO_RINGBUFFER_SIZE];
int sokoUndoRingbufferPos;
int sokoUndoRingbufferCount;

// Emulates upstream's own real "TVText" window/cursor helper on top of
// the flat sokoVram tile[] buffer.
int sokoTextPosX1, sokoTextPosY1, sokoTextPosX2, sokoTextPosY2, sokoTextPosX, sokoTextPosY;
int sokoVram[SOKO_TILES_H * SOKO_TILES_V];

// Plays one representative one-shot tone approximating real upstream's
// own tracker PATTERN for this event - see this file's own "SOUND" header
// comment for why (this shim has no real pattern/track player).
void sokoTriggerFx( int soundId )
{
    if( soundId == SOKO_SOUND_KEY )
      gbPlayTick();
    else if( soundId == SOKO_SOUND_CANT_MOVE )
      gbPlayCancel();
    else if( soundId == SOKO_SOUND_CONGRAT )
      gbPlayOK();
    // SOKO_SOUND_MOVE / SOKO_SOUND_PUSH: no sound, matching upstream's
    // own empty switch cases.
}

// Draws the whole real 16x9 tile grid (each tile a real 5x5 bitmap) -
// direct port of upstream's own `text_draw_screen()`.
void sokoTextDrawScreen()
{
    int x, y;

    gbClear();
    for( x = 0; x < SOKO_TILES_H; x++ )
    {
        for( y = 0; y < SOKO_TILES_V; y++ )
          gbDrawBitmap( x * 5, y * 5, sokoTiles[ sokoVram[ x + y * SOKO_TILES_H ] ] );
    }
}

void sokoTextSetWindow( int x1, int y1, int x2, int y2 )
{
    sokoTextPosX1 = x1;
    sokoTextPosY1 = y1;
    sokoTextPosX2 = x2;
    sokoTextPosY2 = y2;
    sokoTextPosX = x1;
    sokoTextPosY = y1;
}

void sokoTextPutc( int c )
{
    sokoVram[ sokoTextPosX + sokoTextPosY * SOKO_TILES_H ] = c;
    sokoTextPosX++;
    if( sokoTextPosX > sokoTextPosX2 )
    {
        sokoTextPosX = sokoTextPosX1;
        sokoTextPosY++;
        if( sokoTextPosY > sokoTextPosY2 )
          sokoTextPosY = sokoTextPosY1;
    }
}

void sokoTextNextLine()
{
    sokoTextPosX = sokoTextPosX1;
    sokoTextPosY++;
    if( sokoTextPosY > sokoTextPosY2 )
      sokoTextPosY = sokoTextPosY1;
}

// Direct port of upstream's own `text_print_number()` - a fixed-width,
// zero-padded number printed digit-by-digit via gbDrawChar() (real
// upstream used repeated setCursor()+write() calls instead).
void sokoTextPrintNumber( int x, int y, int number, int digits )
{
    int i, j, mul;

    for( i = digits; i > 0; i-- )
    {
        mul = 1;
        for( j = 1; j < i; j++ )
          mul = mul * 10;
        gbDrawChar( '0' + ( ( number / mul ) % 10 ), x + 4 * ( digits - i ), y );
    }
}

void sokoEepromSetLevelDone( int level )
{
    int byteId = 3 + ( level / 8 );
    int bitId = level % 8;
    int value = eeprom_read_byte( byteId );

    value = value | ( 1 << bitId );
    eeprom_write_byte( byteId, value );
}

bool sokoEepromIsLevelDone( int level )
{
    int byteId = 3 + ( level / 8 );
    int bitId = level % 8;

    if( eeprom_read_byte( byteId ) & ( 1 << bitId ) )
      return true;
    return false;
}

void sokoEepromSetLastLevel( int level )
{
    eeprom_write_byte( 1, level & 0xFF );
    eeprom_write_byte( 2, ( level >> 8 ) & 0xFF );
}

int sokoEepromGetLastLevel()
{
    int lastLevel = eeprom_read_byte( 1 ) | ( eeprom_read_byte( 2 ) << 8 );

    if( lastLevel < SOKO_LEVELS_COUNT )
      return lastLevel;
    return 0;
}

void sokoEepromInit()
{
    int i;

    if( eeprom_read_byte( 0 ) != 51 )
    {
        eeprom_write_byte( 0, 51 );
        for( i = 1; i < 3 + ( SOKO_LEVELS_COUNT / 8 + 1 ); i++ )
          eeprom_write_byte( i, 0 );
    }
}

// Loads and draws the level currently pointed to by sokoLevelDataPos -
// direct port of upstream's own `sokoban_load_level()`, decoding the same
// real nibble-compressed format (see this file's own header comment).
void sokoLoadLevel()
{
    int readingPos;
    int token, token1, token2;
    int levelWidth, levelHeight;
    int i, j;

    sokoMovesLevel = 0;
    sokoPushesLevel = 0;

    sokoUndoRingbufferPos = 0;
    sokoUndoRingbufferCount = 0;

    readingPos = sokoLevelDataPos;

    // Real, correct 144-cell bound (SOKO_TILES_H * SOKO_TILES_V) - see
    // this file's own header comment on the real upstream out-of-bounds
    // bug normalized here.
    for( i = 0; i < SOKO_TILES_H * SOKO_TILES_V; i++ )
      sokoVram[ i ] = SOKO_TILE_SKY;

    token = sokoLevels[ readingPos ];
    readingPos++;
    levelWidth = ( ( token & 0xF0 ) >> 4 ) + 1;
    levelHeight = ( token & 0x0F ) + 1;

    sokoTextSetWindow(
        ( SOKO_FIELD_LEFT + SOKO_FIELD_RIGHT - levelWidth ) / 2,
        ( SOKO_FIELD_TOP + SOKO_FIELD_BOTTOM - levelHeight ) / 2,
        ( SOKO_FIELD_LEFT + SOKO_FIELD_RIGHT - levelWidth ) / 2 + levelWidth - 1,
        ( SOKO_FIELD_TOP + SOKO_FIELD_BOTTOM - levelHeight ) / 2 + levelHeight - 1 );

    do
    {
        token = sokoLevels[ readingPos ];
        token1 = ( token & 0xF0 ) >> 4;
        token2 = token & 0x0F;

        if( token1 < 0x0E )
        {
            sokoTextPutc( SOKO_TILE_FLOOR + ( token1 & 0x07 ) );
            if( token1 > 0x07 )
              sokoTextPutc( SOKO_TILE_FLOOR + ( token1 & 0x07 ) );
        }
        else
          sokoTextNextLine();

        if( token2 < 0x0E )
        {
            sokoTextPutc( SOKO_TILE_FLOOR + ( token2 & 0x07 ) );
            if( token2 > 0x07 )
              sokoTextPutc( SOKO_TILE_FLOOR + ( token2 & 0x07 ) );
        }
        else
          sokoTextNextLine();

        readingPos++;
    }
    while( ( token1 != 0x0F ) && ( token2 != 0x0F ) );

    for( i = sokoTextPosX1; i <= sokoTextPosX2; i++ )
    {
        for( j = sokoTextPosY1; j <= sokoTextPosY2; j++ )
        {
            if( sokoVram[ i + j * SOKO_TILES_H ] == SOKO_TILE_SKY )
              sokoVram[ i + j * SOKO_TILES_H ] = SOKO_TILE_FLOOR;
        }
    }

    sokoLevelDone = sokoEepromIsLevelDone( sokoLevel );

    sokoLevelDataPosNext = readingPos;
}

void sokoRestartGame()
{
    sokoLevel = 0;
    sokoLevelDataPos = 0;
    sokoMoves = 0;
    sokoPushes = 0;
    sokoLevelSelectPos = 0;
}

void sokoAdvanceLevel()
{
    sokoLevel++;
    sokoLevelDataPos = sokoLevelDataPosNext;

    if( sokoLevel >= SOKO_LEVELS_COUNT )
      sokoRestartGame();
}

// Returns the vram index[] the player currently stands on, or -1 if not
// found (should never happen against a real, well-formed level).
int sokoFindPlayer()
{
    int i;

    for( i = 0; i < SOKO_TILES_H * SOKO_TILES_V; i++ )
    {
        if( ( sokoVram[ i ] == SOKO_TILE_PLAYER ) || ( sokoVram[ i ] == SOKO_TILE_PLAYER_TARGET ) )
          return i;
    }
    return -1;
}

bool sokoIsLevelCleared()
{
    int i;

    for( i = 0; i < SOKO_TILES_H * SOKO_TILES_V; i++ )
    {
        if( sokoVram[ i ] == SOKO_TILE_BLOCK )
          return false;
    }
    return true;
}

// Undoes the last recorded push - direct port of upstream's own
// `sokoban_undo_last_push()` (see this file's own header comment for the
// pointer-to-index rewrite). If the ring buffer is empty, upstream itself
// falls back to reloading (restarting) the whole level - a real,
// deliberate upstream design choice, preserved exactly.
void sokoUndoLastPush()
{
    int a, b, c, d;

    if( sokoUndoRingbufferCount > 0 )
    {
        if( sokoUndoRingbufferPos > 0 )
          sokoUndoRingbufferPos--;
        else
          sokoUndoRingbufferPos = SOKO_UNDO_RINGBUFFER_SIZE - 1;
        sokoUndoRingbufferCount--;

        a = sokoUndoRingbuffer[ sokoUndoRingbufferPos ].pos;
        b = a + sokoUndoRingbuffer[ sokoUndoRingbufferPos ].offset;
        c = b + sokoUndoRingbuffer[ sokoUndoRingbufferPos ].offset;
        d = sokoFindPlayer();

        sokoVram[ d ] = sokoVram[ d ] - 6;
        sokoVram[ a ] = sokoVram[ a ] + 6;
        sokoVram[ c ] = sokoVram[ c ] - 2;
        sokoVram[ b ] = sokoVram[ b ] + 2;

        sokoMovesLevel++;
        sokoMoves++;
        sokoPushesLevel--;
        sokoPushes--;
    }
    else
      sokoLoadLevel();
}

// Direct port of upstream's own `sokoban_level_select()` screen - real
// two-button-icon (up/down arrow glyph) cursor over 3 digit columns
// (ones/tens/hundreds), moved with LEFT/RIGHT, adjusted with UP/DOWN.
void sokoLevelSelectScreen()
{
    int arrowX;

    gbClear();

    gbCursorX = 0;
    gbCursorY = 10;
    gbPrintString( "Select level:" );

    arrowX = 60 - sokoLevelSelectPos * 4;
    gbDrawChar( 30, arrowX, 6 );
    gbDrawChar( 31, arrowX, 14 );

    gbDrawChar( '0' + ( ( sokoLevel + 1 ) % 10 ), 60, 10 );
    gbDrawChar( '0' + ( ( ( sokoLevel + 1 ) / 10 ) % 10 ), 60 - 4, 10 );
    gbDrawChar( '0' + ( ( ( sokoLevel + 1 ) / 100 ) % 10 ), 60 - 8, 10 );

    gbCursorX = 0;
    gbCursorY = 25;
    if( sokoEepromIsLevelDone( sokoLevel ) )
      gbPrintString( "Finished" );
    else
      gbPrintString( "Not finished" );

    if( gbRepeat( BTN_LEFT, 5 ) )
    {
        sokoLevelSelectPos++;
        sokoTriggerFx( SOKO_SOUND_KEY );
        if( sokoLevelSelectPos > 2 )
        {
            sokoLevelSelectPos = 2;
            sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
        }
    }

    if( gbRepeat( BTN_RIGHT, 5 ) )
    {
        sokoLevelSelectPos--;
        sokoTriggerFx( SOKO_SOUND_KEY );
        if( sokoLevelSelectPos < 0 )
        {
            sokoLevelSelectPos = 0;
            sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
        }
    }

    if( gbRepeat( BTN_DOWN, 5 ) )
    {
        if( sokoLevelSelectPos == 0 )
        {
            if( sokoLevel >= 1 )
            {
                sokoLevel--;
                sokoTriggerFx( SOKO_SOUND_KEY );
            }
            else
            {
                sokoLevel = 0;
                sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
            }
        }
        else if( sokoLevelSelectPos == 1 )
        {
            if( sokoLevel >= 10 )
            {
                sokoLevel -= 10;
                sokoTriggerFx( SOKO_SOUND_KEY );
            }
            else
            {
                sokoLevel = 0;
                sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
            }
        }
        else
        {
            if( sokoLevel >= 100 )
            {
                sokoLevel -= 100;
                sokoTriggerFx( SOKO_SOUND_KEY );
            }
            else
            {
                sokoLevel = 0;
                sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
            }
        }
    }

    if( gbRepeat( BTN_UP, 5 ) )
    {
        if( sokoLevelSelectPos == 0 )
        {
            sokoLevel++;
            sokoTriggerFx( SOKO_SOUND_KEY );
        }
        else if( sokoLevelSelectPos == 1 )
        {
            sokoLevel += 10;
            sokoTriggerFx( SOKO_SOUND_KEY );
        }
        else
        {
            sokoLevel += 100;
            sokoTriggerFx( SOKO_SOUND_KEY );
        }

        if( sokoLevel >= SOKO_LEVELS_COUNT )
        {
            sokoLevel = SOKO_LEVELS_COUNT - 1;
            sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
        }
    }

    if( gbPressed( BTN_A ) || gbPressed( BTN_B ) )
    {
        int levelToLoad;
        int i;

        sokoTriggerFx( SOKO_SOUND_KEY );

        levelToLoad = sokoLevel;
        sokoRestartGame();
        for( i = 0; i < levelToLoad; i++ )
        {
            sokoLoadLevel();
            sokoAdvanceLevel();
        }
        sokoLoadLevel();
        sokoEepromSetLastLevel( sokoLevel );

        sokoGuiState = SOKO_STATE_GAME;
    }
}

// Direct port of upstream's own `sokoban_move()`.
void sokoMove()
{
    int a, b, c;
    int offset;

    offset = 0; // always overwritten below before use - see the early
                // return a few lines down, which guarantees at least one
                // direction button is held whenever offset is read.

    if( gbPressed( BTN_LEFT ) ) offset = SOKO_OFFSET_LEFT;
    if( gbPressed( BTN_RIGHT ) ) offset = SOKO_OFFSET_RIGHT;
    if( gbPressed( BTN_UP ) ) offset = SOKO_OFFSET_UP;
    if( gbPressed( BTN_DOWN ) ) offset = SOKO_OFFSET_DOWN;

    if( gbPressed( BTN_A ) )
    {
        if( sokoMovesLevel == 0 )
          sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
        else
          sokoTriggerFx( SOKO_SOUND_KEY );
        sokoUndoLastPush();
    }

    if( gbPressed( BTN_B ) )
    {
        if( sokoMovesLevel == 0 )
          sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
        else
          sokoTriggerFx( SOKO_SOUND_KEY );
        sokoLoadLevel();
    }

    if( gbPressed( BTN_C ) )
      sokoGuiState = SOKO_STATE_LEVELS;

    if( !gbPressed( BTN_LEFT ) && !gbPressed( BTN_RIGHT ) && !gbPressed( BTN_UP ) && !gbPressed( BTN_DOWN ) )
      return;

    a = sokoFindPlayer();
    b = a + offset;
    c = b + offset;

    if( ( sokoVram[ b ] >= SOKO_TILE_FLOOR ) && ( sokoVram[ c ] >= SOKO_TILE_FLOOR ) &&
        ( ( sokoVram[ b ] <= SOKO_TILE_TARGET ) ||
          ( ( sokoVram[ b ] <= SOKO_TILE_BLOCK_TARGET ) && ( sokoVram[ c ] <= SOKO_TILE_TARGET ) ) ) )
    {
        sokoMoves++;
        sokoMovesLevel++;
        sokoVram[ a ] = sokoVram[ a ] - 6;

        if( sokoVram[ b ] >= SOKO_TILE_BLOCK )
        {
            sokoTriggerFx( SOKO_SOUND_PUSH );

            sokoUndoRingbuffer[ sokoUndoRingbufferPos ].pos = a;
            sokoUndoRingbuffer[ sokoUndoRingbufferPos ].offset = offset;
            if( sokoUndoRingbufferCount < SOKO_UNDO_RINGBUFFER_SIZE )
              sokoUndoRingbufferCount++;
            sokoUndoRingbufferPos = ( sokoUndoRingbufferPos + 1 ) % SOKO_UNDO_RINGBUFFER_SIZE;

            sokoPushes++;
            sokoPushesLevel++;
            sokoVram[ b ] = sokoVram[ b ] - 2;
            sokoVram[ c ] = sokoVram[ c ] + 2;
        }
        else
          sokoTriggerFx( SOKO_SOUND_MOVE );

        sokoVram[ b ] = sokoVram[ b ] + 6;
    }
    else
      sokoTriggerFx( SOKO_SOUND_CANT_MOVE );
}

