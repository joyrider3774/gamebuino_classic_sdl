void gameSokobuino_init()
{
    int lastLevel;
    int i;

    gbBegin();

    sokoEepromInit();
    sokoRestartGame();

    lastLevel = sokoEepromGetLastLevel();
    for( i = 0; i < lastLevel; i++ )
    {
        sokoLoadLevel();
        sokoAdvanceLevel();
    }
    sokoLoadLevel();

    sokoGuiState = SOKO_STATE_INTRO;
}

void gameSokobuino_update()
{
    if( !gbUpdate() ) return;

    if( sokoGuiState == SOKO_STATE_INTRO )
      sokoShowIntro();
    else if( sokoGuiState == SOKO_STATE_GAME )
    {
        sokoMove();
        sokoTextDrawScreen();

        if( sokoIsLevelCleared() )
        {
            sokoLevelDone = 1;
            sokoEepromSetLevelDone( sokoLevel );
            sokoCongratulations();
        }
    }
    else if( sokoGuiState == SOKO_STATE_LEVELS )
      sokoLevelSelectScreen();
    else if( sokoGuiState == SOKO_STATE_CONGRATS )
      sokoShowCongratulations();

    gbRenderFrame();
}
