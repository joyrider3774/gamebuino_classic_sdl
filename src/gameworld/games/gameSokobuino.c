// Sokobuino (martinsustek, license: none specified upstream - recovered
// via direct download, no live GitHub repo with real source). A real,
// complete Sokoban clone: 600 real levels (bundled from Microban/
// Sasquatch by David W. Skinner and procedurally-generated sets by Joshua
// Taylor/Ian Parberry - real upstream credits both, reproduced verbatim on
// this port's own intro screen), a real EEPROM-backed "last played level"/
// "level finished" save, and a real undo-last-push ring buffer.
//
// Every real `gb.x.y(...)` call site is mechanically rewritten to a plain
// `gbY(...)` call (this dialect has no classes/methods - see gamePong.c's
// own header comment). Every global/function got a `soko`-prefixed name
// (this cartridge has one flat namespace shared across every game).
// Upstream's own binary-literal bit masks (`0b11110000`, `0b00001111`,
// `0b00000111`) became `0xF0`/`0x0F`/`0x07` hex (no binary literals in
// this dialect - see VIRCON32_C_DIALECT.md). Upstream's own `uint8_t`/
// `int8_t`/`uint16_t` all became plain `int` (this dialect's own
// avrCompat.h aliasing - every type is one 32-bit word regardless).
// Upstream's own two real `switch` statements (in the level-select
// screen's own D-pad handling) became if/else-if chains, matching this
// project's own established "no switch statement proven to work in this
// dialect" convention (see gameShipwrek.c's own header comment).
//
// DATA: the real `sokoban_tiles[][7]` bitmap table (8 real 5x5 tile
// glyphs - floor/target/box/box-on-target/sky/wall/player/player-on-
// target) and the real, full 600-level `sokoban_levels[]` compressed
// level-data table (14276 real bytes) are both copied verbatim as
// `sokoTiles`/`sokoLevels` - every byte was already a real hex literal
// upstream, so no binary-to-hex conversion was needed for either table.
// `sokoTiles[]` is already real Gamebuino `Display::drawBitmap()` format
// (width, height, then packed row bytes) - the exact format this shim's
// own `gbDrawBitmap()` expects directly, so each tile draws via a direct
// `gbDrawBitmap(x, y, sokoTiles[tileId])` call, matching upstream's own
// `gb.display.drawBitmap(x*5, y*5, sokoban_tiles[vram[...]])` call
// exactly (see gameBlobAttack.c's own `blobTileBitmaps[idx]` for the same
// "2D bitmap table indexed by tile id" pattern already proven here).
//
// POINTERS -> INDICES: upstream represents playfield positions and level-
// data read positions as real `char*`/`unsigned char*` pointers
// (`sokoban_find_player()` returns a pointer, `sokoban_move()`'s own
// `a`/`b`/`c` tile pointers, `sokoban_level_data_pointer`), including one
// real pointer-minus-pointer computation (`sokoban_undo_ringbuffer[...]
// .pos = a - vram;`) that this dialect's compiler does not support (see
// VIRCON32_C_DIALECT.md - "no pointer-minus-pointer arithmetic"). Ported
// throughout as plain `int` indices into `sokoVram[]`/`sokoLevels[]`
// instead of pointers - a direct index-for-pointer substitution with
// identical arithmetic (`a + offset` becomes an index add either way),
// and the one pointer-subtraction site becomes a plain index store
// (`.pos = a;`, since `a` is already the index upstream had to subtract
// `vram` back out of its own pointer to get).
//
// A REAL UPSTREAM BUG FOUND AND NORMALIZED (not preserved): `sokoban_
// load_level()`'s own screen-clear loop runs `for (uint8_t i = 0; i <
// 16*12; i++) vram[i] = FONT_SOKOBAN_SKY;` - 192 iterations against a
// `vram[]` array upstream itself only ever declares as `SCREEN_TILES_H *
// SCREEN_TILES_V` = 16*9 = 144 bytes (confirmed directly against
// upstream's own declaration). On real AVR hardware this silently
// overwrites whatever 48 bytes of RAM happen to sit immediately after
// `vram[]` in that specific build's own linked memory layout - undefined,
// unpredictable, and entirely an artifact of AVR-GCC's own real link
// order, not a real gameplay mechanic a player could ever observe or a
// behavior this port could faithfully reproduce (Vircon32's own global
// memory layout shares nothing with AVR's, so "porting" this write would
// just corrupt a different, arbitrary variable here instead). Normalized
// to the real, correct 144 (`SOKO_TILES_H * SOKO_TILES_V`) bound instead.
//
// DEAD CODE DROPPED: `sokoban_skip_to_previous_level()` (defined upstream,
// never once called from anywhere in the real source) and `free_ram()`/
// `display_free_ram()` (an AVR-specific `__heap_start`/`__brkval` debug
// helper - real upstream's own only call site is already commented out,
// `//display_free_ram();`, in real `loop()`) are both genuinely dead code
// upstream itself never exercises - dropped rather than ported, since
// `free_ram()`'s own AVR linker symbols have no Vircon32 equivalent to
// port to in the first place. `TriggerFx()`'s own unused `volume`/
// `param3` parameters (every real call site passes `0xff`/`false`, and
// the function's own body never reads either one) were dropped too.
//
// SOUND - approximated, real scope limit (see this project's own
// CLAUDE.md "Open questions"): real upstream plays 3 short real tracker
// PATTERNS (`gb.sound.playTrack()` against `trackPush`/`trackCantMove`/
// `trackCongrat`, each a real multi-note sequence), not simple one-shot
// tones - this shim only ports one-shot representative tones, not the
// real pattern/track player (matching gameStarships101.c's own identical
// real scope limit and its own established substitution convention).
// `trackPush` (played on every real "key" acknowledgement: successful
// level-select navigation, a genuine undo, a level restart) is
// approximated with `gbPlayTick()`; `trackCantMove` (a real negative/
// blocked cue) with `gbPlayCancel()`; `trackCongrat` (a real ascending
// 11-note win fanfare) with `gbPlayOK()` - matching gameStarships101.c's
// own precedent of `gbPlayOK()`/`gbPlayCancel()` for a real win/lose
// jingle substitute. `SOKOBAN_SOUND_MOVE`/`_PUSH` play no sound at all
// upstream either (an empty real `switch` case) - ported as no call at
// all, not a silent substitute.
//
// EEPROM: a real, genuine EEPROM consumer - `eeprom_read_byte()`/
// `eeprom_write_byte()` port upstream's own real `EEPROM.read()`/
// `EEPROM.write()` byte-for-byte, same real address layout (byte 0 = a
// magic-number-51 initialized flag, bytes 1-2 = last-played level index
// LSB/MSB, bytes 3 onward = one real bit per level's "finished" flag, 600
// levels = 75 bytes = bytes 3-77) - real address range 0-77, well inside
// this shim's own real 0-1023 EEPROM address space. Upstream's own raw
// `EEPROM.write(2, level >> 8)` relies on real AVR `EEPROM.write()`'s
// own implicit `uint8_t` parameter truncation; this shim's own
// `eeprom_write_byte()` does not truncate for you, so both bytes are
// masked explicitly with `& 0xFF` here (matching gameUfoRace.c's own
// identical real EEPROM high-score write convention).
//
// FONT: upstream never calls `setFont()` - it just inherits real
// hardware's own default font (real `font3x5`, a 4x6 real cell including
// spacing), confirmed directly by upstream's own real pixel math (e.g.
// `text_print_number()`'s own real 4px-per-digit `x + 4 * (digits - i)`
// step, and `show_intro()`'s own real full-width 21-character line at
// `21*4 = 84px` exactly matching the real 84px-wide LCD) - this port
// likewise never calls `gbSetFont()`, inheriting this shim's own matching
// real `gbFont3x5` default. The real up/down arrow icon glyphs (ASCII 30/
// 31) and single-digit glyphs upstream draws via `gb.display.write(...)`
// after a `setCursor()` call are ported as direct `gbDrawChar(ch, x, y)`
// calls at the same real pixel coordinates.
//
// CONTROLS: unmodified from upstream - D-pad moves the player (last-
// pressed-wins if multiple direction buttons are held on the same real
// tick, exactly matching upstream's own real sequential-`if`-with-no-
// `else` dispatch order LEFT/RIGHT/UP/DOWN, preserved as-is rather than
// "fixed" into a direction-priority scheme upstream itself never had),
// A undoes the last real push (or, if the real undo ring buffer is
// empty, restarts the level outright - a real, deliberate upstream
// fallback, not a bug), B restarts the current level, C opens the real
// level-select screen.

