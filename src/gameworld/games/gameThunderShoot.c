// Thunder Shoot (Awot83 / Awot, GPLv3 - github.com/Awot83/Gamebuino-Thunder-Shoot).
// A horizontally-scrolling road-combat shoot-'em-up: an airborne ship flies
// over an endlessly scrolling horizon/road background, dodging and shooting
// wandering enemy ships, convoys of cars, a boss robot and a boss turtle -
// the two bosses and the car convoy cycle in a fixed real upstream sequence
// (enemy ships loop 6 times -> robot boss arrives -> once destroyed, the
// turtle boss arrives -> once destroyed, back to enemy ships) via the real
// `ENEMY` phase counter (`thundEnemyPhase` below, values 0/1/2). A single
// real `Thunder_shoot.ino` source file (`setup()`/`loop()`, no further
// upstream functions at all - every real behavior lives directly in
// `loop()`), so this port is the same shape: one `thundUpdatePlay()`
// function holding the whole real per-tick body, translated block-for-block
// in upstream's own original order.
//
// DIALECT REWRITES: every real `gb.x.y(...)` call site is mechanically
// rewritten to a plain `gbY(...)` function call (see gamePong.c's own
// header comment - this dialect has no classes/methods/operator
// overloading). `random(N)`/`random(a,b)` became `arand(N)`/`a+arand(b-a)`
// (this project's own established RNG helper, matching real Arduino
// `random()`'s own `[min,max)` range semantics). `byte` fields became plain
// `int` (no genuinely boolean use of `byte` anywhere in this game, unlike
// gameAgaruino.c's own case). `const byte NAME PROGMEM[] = {w,h,...}` bitmap
// tables were copied byte-for-byte into `int thundNameBitmap[N] = {w,h,...}`
// arrays (`gbDrawBitmap()`'s own real expected format, matching real
// `Display::drawBitmap()`'s own width/height-prefixed layout exactly - no
// bit-repacking needed) via a small script that parsed the real .ino source
// directly and converted every real `B`-binary literal to hex (upstream
// mixes both `B00010100`-style binary and `0x14`-style hex literals across
// different arrays, sometimes for the exact same sprite re-declared twice -
// see "TWO DECLARATIONS PER BACKGROUND SPRITE" below) - every one of the 39
// real sprites this game actually draws is ported this way, none dropped to
// a placeholder. `const byte* NAME[N] = {...}` sprite-pointer tables became
// real `int* thundXxxSprites[N] = {...}` arrays (already proven working
// elsewhere in this project, e.g. gameDescent.c's own `descentPlayerSprites`).
// `gb.buttons.repeat(BTN_x, 1)` ported unchanged to `gbRepeat(BTN_x, 1)` -
// real hardware's own `period<=1` case fires every single held tick (see
// gamebuinoShim.h's own header comment on `gbRepeat()`), exactly the
// continuous per-tick movement/fire upstream relies on for ship movement
// and rapid-fire shooting alike.
//
// TWO DECLARATIONS PER BACKGROUND SPRITE, ONE ACTUALLY USED: upstream
// declares `horizon2`/`cloud1`/`cloud1b` two or three times each (some
// copies commented out, `//const byte horizon2[]...`), evidently kept
// around from earlier art iterations - only the real final, uncommented
// declaration of each name was ported (`thundHorizon2Bitmap`/
// `thundCloud1Bitmap`), matching whichever body upstream's own compiler
// would actually see. `cloud1b` and `CAR1X`/`CAR2X`/`CAR3X`/`CAR4X`/`CAR5X`
// (five real "X" variant car sprites) are declared upstream but never once
// passed to `drawBitmap()` anywhere in `loop()` - confirmed directly by
// grepping the whole real source for each name - so these six real dead
// sprite tables were not ported at all (zero observable effect either way,
// since real hardware never draws them either).
//
// SEVERAL REAL DEAD VARIABLES, DROPPED: `TempoCloud`, `k`, `bullet_tempo`,
// `isShoot`, `DeplacementX`, `RandDistCar3` and `StayingTurtle` are all
// declared upstream, assigned at most once (an initializer or a single
// reset in `setup()`), and never actually read by any real logic anywhere
// in `loop()` - confirmed directly by grepping the whole real source for
// each name. Dropping them has zero observable effect on real gameplay, so
// they are not ported (this project's own established bar for silently
// normalizing away dead upstream state - see this file's own porting-rules
// reference). `ExplodedRobot`/`ExplodedTurtle` are similarly write-only
// (set once each on a boss kill, never read again) but cost nothing to keep
// as literal state, so they ARE ported below (`thundExplodedRobot`/
// `thundExplodedTurtle`) purely for upstream fidelity, not because
// anything reads them.
//
// A GENUINE UPSTREAM COLLISION BUG, PRESERVED: car 3's bullet-collision
// check (`thundCheckCarCollisions()` below) tests against
// `DeplacementCars - 65 - RandDistCar1`, reusing car 2's own real random
// gap variable instead of car 3's own `RandDistCar2` - car 3's own real
// draw/fill-rect position two blocks earlier in the same real source both
// correctly use `RandDistCar2`, so this is a genuine one-line real upstream
// typo, not a deliberate design choice. Its real effect: whenever
// `RandDistCar1 != RandDistCar2` (`random(1,20)` each, rarely equal), car
// 3's hitbox is checked at a slightly wrong x - some real shots that
// visually connect miss, and vice versa. Preserved exactly
// (`thundRandDistCar1` reused in car 3's own collision check below, exactly
// where upstream has it) rather than "fixed" into behavior real hardware
// never actually shipped, matching this project's own established norm for
// real, load-bearing gameplay bugs.
//
// A GENUINE UPSTREAM DEAD FEATURE, PRESERVED AS COSMETIC-ONLY: the "power
// bar" (Button B charges it, a screen-edge-to-ship beam triangle flickers
// once full) never actually damages anything - no real collision check
// anywhere in upstream tests the beam against any enemy/boss/car. Ported
// exactly as a cosmetic-only beam (`thundUpdatePower()` below) rather than
// inventing real damage upstream never implemented. The real flicker
// condition itself has a similar gap preserved verbatim: `j>50` draws an
// outline triangle, `j<50` draws a filled one, and `j==50` draws nothing at
// all for that one tick (a 1-in-101 chance per tick, from `random(0,100)`
// - real upstream's own `j`, never `==`-checked) - kept exactly as
// upstream wrote it.
//
// TITLE SCREEN: upstream's own blocking `gb.titleScreen(F("THUNDER
// SHOOT"))` (called once in `setup()`, and again on every real Button-C
// press mid-game, which upstream implements as a full `setup()` re-call)
// became an explicit `THUND_STATE_TITLE` state, matching the "blocking
// call -> explicit resumable state" treatment used throughout this project
// (see gamePong.c's own header comment) - dismissed by Button A (real
// `titleScreen()`'s own real dismiss button). A real, commented-out
// `//gb.popup(F("LET'S GO !!"), 10);` immediately below upstream's own
// `titleScreen()` call is genuine dead code (never executes on real
// hardware either) and was not ported.
//
// GAME OVER IS NOT A SEPARATE STATE: a real, confirmed upstream design
// choice, not a porting simplification - once `NBLIFES` reaches 0, `loop()`
// keeps running every other real system unconditionally (cars/enemies/
// bullets/scrolling all keep moving) while additionally drawing the real
// GAMEOVER bitmap and score text on top every frame - there is no early
// `return`/state change anywhere in upstream's own game-over branch.
// Reproduced exactly (`thundUpdatePlay()` below has no early-out for
// `thundLives <= 0` either) - the only way out is a real Button-C press,
// which fully resets everything via `thundResetGame()` and returns to the
// title state.
//
// `gb.battery.show = false;` was dropped outright (a real hardware-only
// cosmetic battery-icon setting with no shim equivalent, matching this
// project's established norm for this exact upstream line - see e.g.
// gamePong.c/gameDescent.c's own header comments). Upstream never calls
// `gb.display.setFont(...)` anywhere, so this port inherits this shim's own
// real `gbFont3x5` default unchanged, matching this project's own
// established "don't invent a font choice upstream never made" rule.

