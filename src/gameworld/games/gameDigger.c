bool digTestMove( int x, int y, int monster )
{
    if( monster == DIG_MONSTER_U )
    {
        if( digWorldGet( x, y - 1 ) == DIG_PLAYER ) digDie();
        if( digWorldGet( x, y - 1 ) == DIG_EMPTY ) return true;
        return false;
    }
    if( monster == DIG_MONSTER_L )
    {
        if( digWorldGet( x - 1, y ) == DIG_PLAYER ) digDie();
        if( digWorldGet( x - 1, y ) == DIG_EMPTY ) return true;
        return false;
    }
    if( monster == DIG_MONSTER_D )
    {
        if( digWorldGet( x, y + 1 ) == DIG_PLAYER ) digDie();
        if( digWorldGet( x, y + 1 ) == DIG_EMPTY ) return true;
        return false;
    }
    if( monster == DIG_MONSTER_R )
    {
        if( digWorldGet( x + 1, y ) == DIG_PLAYER ) digDie();
        if( digWorldGet( x + 1, y ) == DIG_EMPTY ) return true;
        return false;
    }
    return true;
}

int digGetNewDirection( int x, int y )
{
    int type;
    int sprite;

    type = digWorldGet( x, y ) & DIG_TYPEMASK;
    sprite = digWorldGet( x, y ) & DIG_SPRITEMASK;

    if( type == DIG_TYPE_UD )
    {
        if( sprite == DIG_MONSTER_D ) sprite = DIG_MONSTER_U;
        else sprite = DIG_MONSTER_D;
    }
    else if( type == DIG_TYPE_LR )
    {
        if( sprite == DIG_MONSTER_R ) sprite = DIG_MONSTER_L;
        else sprite = DIG_MONSTER_R;
    }
    else if( type == DIG_TYPE_RT )
    {
        while( !digTestMove( x, y, sprite ) )
        {
            sprite = sprite + 1;
            if( sprite > DIG_MONSTER_R ) sprite = DIG_MONSTER_D;
        }
    }
    else if( type == DIG_TYPE_LT )
    {
        while( !digTestMove( x, y, sprite ) )
        {
            sprite = sprite - 1;
            if( sprite < DIG_MONSTER_D ) sprite = DIG_MONSTER_R;
        }
    }

    return sprite + type;
}

void digMoveMonster( int x, int y, int sprite )
{
    int target;

    if( ( gbFrameCount % 10 ) == 0 )
    {
        if( digWorldGet( x - 1, y ) > DIG_EMPTY && digWorldGet( x + 1, y ) > DIG_EMPTY && digWorldGet( x, y - 1 ) > DIG_EMPTY && digWorldGet( x, y + 1 ) > DIG_EMPTY )
          return; // no way out

        // straight forward preferred, if not: search new direction
        if( sprite == DIG_MONSTER_D )
        {
            target = digWorldGet( x, y + 1 ) & DIG_SPRITEMASK;
            if( target == DIG_EMPTY ) { digWorldSet( x, y + 1, digWorldGet( x, y ) | DIG_MOVINGSTATE ); digWorldSet( x, y, DIG_EMPTY ); }
            else if( target == DIG_PLAYER ) digDie();
            else digWorldSet( x, y, digGetNewDirection( x, y ) );
        }
        if( sprite == DIG_MONSTER_U )
        {
            target = digWorldGet( x, y - 1 ) & DIG_SPRITEMASK;
            if( target == DIG_EMPTY ) { digWorldSet( x, y - 1, digWorldGet( x, y ) | DIG_MOVINGSTATE ); digWorldSet( x, y, DIG_EMPTY ); }
            else if( target == DIG_PLAYER ) digDie();
            else digWorldSet( x, y, digGetNewDirection( x, y ) );
        }
        if( sprite == DIG_MONSTER_L )
        {
            target = digWorldGet( x - 1, y ) & DIG_SPRITEMASK;
            if( target == DIG_EMPTY ) { digWorldSet( x - 1, y, digWorldGet( x, y ) | DIG_MOVINGSTATE ); digWorldSet( x, y, DIG_EMPTY ); }
            else if( target == DIG_PLAYER ) digDie();
            else digWorldSet( x, y, digGetNewDirection( x, y ) );
        }
        if( sprite == DIG_MONSTER_R )
        {
            target = digWorldGet( x + 1, y ) & DIG_SPRITEMASK;
            if( target == DIG_EMPTY ) { digWorldSet( x + 1, y, digWorldGet( x, y ) | DIG_MOVINGSTATE ); digWorldSet( x, y, DIG_EMPTY ); }
            else if( target == DIG_PLAYER ) digDie();
            else digWorldSet( x, y, digGetNewDirection( x, y ) );
        }
    }
}

