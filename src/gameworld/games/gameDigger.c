// -----------------------------------------------------------------------------
// Digger.ino - level (de)serialization. digGetBits() reads `pos = levels[
// _level] + codepos/8` then `pgm_read_byte(pos)`/`pgm_read_byte(pos+1)` in
// upstream - ported here as direct array indexing (`data[base]`/
// `data[base+1]`) instead of pointer arithmetic + dereference, since no
// pointer-arithmetic-then-dereference has been proven in this dialect
// anywhere in this project (only single pointer variables/parameters), and
// plain indexing is exactly equivalent semantically.
// -----------------------------------------------------------------------------

int digGetBits( int* data, int bits )
{
    int base;
    int w;

    base = digCodepos / 8;
    w = data[ base ] * 256 + data[ base + 1 ];
    w = w >> ( 16 - ( digCodepos % 8 ) - bits );
    w = w & ( ( 1 << bits ) - 1 );
    digCodepos = digCodepos + bits;

    return w;
}

void digSetTile( int sprite )
{
    int x;
    int y;
    int val;

    x = digWorldpos % DIG_WORLD_W;
    y = digWorldpos / DIG_WORLD_W;
    val = sprite;

    if( sprite == DIG_MONSTER_RT ) val = DIG_MONSTER_R | DIG_TYPE_RT;
    else if( sprite == DIG_MONSTER_LT ) val = DIG_MONSTER_L | DIG_TYPE_LT;
    else if( sprite == DIG_MONSTER_D ) val = DIG_MONSTER_D | DIG_TYPE_UD;
    else if( sprite == DIG_MONSTER_U ) val = DIG_MONSTER_U | DIG_TYPE_UD;
    else if( sprite == DIG_MONSTER_L ) val = DIG_MONSTER_L | DIG_TYPE_LR;
    else if( sprite == DIG_MONSTER_R ) val = DIG_MONSTER_R | DIG_TYPE_LR;

    digWorldSet( x, y, val );

    if( sprite == DIG_PLAYER )
    {
        digCursorX = x;
        digCursorY = y;
    }
}

void digInitWorld( int level )
{
    int* data;
    int i;
    int c;
    int r;
    int refpos;

    data = digGetLevelData( level );

    digDiamonds = 0;
    digCodepos = 0;
    digWorldpos = 0;
    digDiamsNeed = digGetBits( data, 8 );

    while( digWorldpos < DIG_WORLD_H * DIG_WORLD_W )
    {
        if( digGetBits( data, 1 ) )
        {
            r = digGetBits( data, DIG_BITREF );
            c = digGetBits( data, DIG_BITCOUNT ) + DIG_MINMATCH;

            for( i = 0; i < c; i = i + 1 )
            {
                if( digWorldpos < DIG_WORLD_W * DIG_WORLD_H )
                {
                    refpos = digWorldpos - r;
                    digSetTile( digWorldGet( refpos % DIG_WORLD_W, refpos / DIG_WORLD_W ) );
                    digWorldpos = digWorldpos + 1;
                }
            }
        }
        else
        {
            digSetTile( digGetBits( data, DIG_CODELENGTH ) );
            digWorldpos = digWorldpos + 1;
        }
    }
}

void digNextLevel()
{
    if( digCurLevel < DIG_NUM_LEVELS - 3 )
    {
        if( digGamemode == DIG_EASY ) digCureasy = digCureasy + 1;
        else digCurhard = digCurhard + 1;

        digMaxeasy = gbMax( digMaxeasy, digCureasy );
        digMaxhard = gbMax( digMaxhard, digCurhard );
        digCurLevel = digCurLevel + 1;
    }
    digInitWorld( digCurLevel );
}

