// Digger (scmar, no license specified - github.com/scmar/Digger). A real
// Boulder Dash-style game: dig through soil, dodge/exploit falling rocks
// and diamonds, avoid (or crush) patrolling monsters, collect enough
// diamonds to open the exit door, all across 151 real, distinct hand-
// authored levels plus a hidden "the end"/"game over" bonus screen pair.
// Source is 5 real upstream `.ino` tabs sharing one translation unit
// (Digger.ino/Monster.ino/Physics.ino/Player.ino/Render.ino) plus 3 real
// headers (Defines.h/sprites.h/Level.h) - all read in full before writing
// this port.
//
// -----------------------------------------------------------------------------
// Dialect rewrites
// -----------------------------------------------------------------------------
// Every real `gb.x.y(...)` call site was mechanically rewritten to a plain
// `gbY(...)` function call (this dialect has no classes/methods - see
// gamebuinoShim.h's own header comment): `gb.buttons.pressed/held/repeat()`
// -> `gbPressed/gbHeld/gbRepeat()`, `gb.sound.playTick/playOK/playCancel()`
// -> `gbPlayTick/gbPlayOK/gbPlayCancel()`, `gb.display.setColor/fillRect/
// drawBitmap/print()` -> `gbSetColor/gbFillRect/gbDrawBitmap/gbPrintString/
// gbPrintNumber()`, `EEPROM.read/write()` -> `eeprom_read_byte/
// eeprom_write_byte()` (real addresses 0-9 unchanged - this shim's own
// EEPROM slot is a full real 1024 bytes, matching real ATmega328 hardware).
// `max()` (Arduino macro) -> `gbMax()` (no ternary operator in this dialect
// either, so every upstream `a ? b : c` became an explicit if/else - see
// e.g. digGetNewDirection()/digMenuExecute() below). Every real `switch`
// statement (setTile()'s sprite dispatch, moveMonster()'s/falling()'s/
// testMove()'s own direction dispatch, updatePhysics()'s own per-tile
// dispatch) became an if/else-if chain (no switch in this dialect). All
// `byte`/`char` upstream types became plain `int` (avrCompat.h aliases
// every AVR fixed-width type to int anyway); `bool` is a genuine primitive
// here (confirmed via avrCompat.h's own header comment - Vircon32 has 4
// primitive types: int/float/bool/void) so `dead`/`gamemode` stayed `bool`
// verbatim. `random(N)` doesn't appear in this source at all (Digger has
// no RNG use) so `arand()` was never needed.
//
// **The world grid was flattened from a real `byte world[WORLD_W][WORLD_H]`
// 2D array to a 1D `int[280] digWorld` with manual `y*DIG_WORLD_W+x`
// indexing via digWorldGet()/digWorldSet()** - no 2D array declaration
// syntax has been proven anywhere in this project (checked gameConduit.c/
// gameAsterocks.c directly per instructions - neither uses one), matching
// gameMaze.c's own established `mazeIsSet()`/`mazeGridSet()` precedent for
// exactly this situation (a flattened bit/byte grid behind get/set helper
// functions). Every one of upstream's `world[x][y]` reads/writes across all
// 5 files was mechanically rewritten to `digWorldGet(x,y)`/
// `digWorldSet(x,y,v)`.
//
// **Two real pointer-array lookup tables were rewritten as if-chain
// functions instead**, matching this project's own established precedent
// for exactly this situation (gameBlockdude.c's `dudeGetMapData()`,
// gameKillrace.c's `killCarBitmap()`/`killManBitmap()` - both call out that
// no pointer-ARRAY declaration syntax has been proven in this dialect,
// only single pointer variables/parameters/returns):
// - upstream's real `const byte *levels[NUM_LEVELS]` (152 slots) ->
//   `digGetLevelData(index)`, an if-chain over the 151 real level blobs
//   (see the real-bug note on NUM_LEVELS below for why 151, not 152).
// - upstream's real `const byte* sprites[NUM_SPRITES]` (21 slots) ->
//   `digGetSpriteBitmap(idx)`, an if-chain over 17 real distinct bitmaps
//   (upstream's own `monster`/`player` bitmaps in sprites.h are real but
//   genuinely dead code - never referenced by the real `sprites[]` table
//   at all, which points index 11's "player" slot at `digger_d` instead -
//   omitted here as dead weight, matching this project's own established
//   norm for confirmed-unreachable upstream data). `DIG_STATEMASK` (defined
//   in upstream's own Defines.h) is similarly real but never actually used
//   anywhere in any of the 5 source files - kept here anyway for exact
//   constant-for-constant fidelity since it costs nothing.
//
// **Upstream's own blocking `gb.titleScreen(F("DIGGER"))`** (called once at
// boot, and again from inside the pause menu's own real cancel path - see
// below) **and blocking `gb.menu(menu, MENULENGTH)`** (neither has a shim
// equivalent - this shim has no generic menu/title-screen widget at all,
// by design, matching every other ported game here) were converted into an
// explicit state machine: `digState` (DIG_STATE_TITLE at boot, then
// DIG_STATE_PLAY for the rest of the game - dismissed by a genuine
// `gbPressed(BTN_A)`, matching every other port's own title-screen
// convention) plus upstream's own real `gamestate` byte (RUNNING/PAUSED/
// GAMEOVER, ported verbatim as `digGamestate`) for the inner game state,
// plus two new port-only fields (`digMenuTitleActive`/`digMenuCursor`) for
// the hand-rolled pause-menu screen itself (see below). The real pause
// menu's own 7 text items/vertical-list layout/`>` cursor marker are a
// bespoke replacement with no per-pixel upstream data to restore - matching
// gameConduit.c's own precedent for exactly this situation (a hand-rolled
// stand-in for the *generic* `gb.menu()` widget, not a per-game screen).
//
// **The real `gb.menu()`/`gb.titleScreen()` widgets' own exact button
// semantics were read directly from the real library source**
// (`more games/Gamebuino-Classic/Gamebuino.cpp`'s own `Gamebuino::menu()`/
// `Gamebuino::titleScreen()`) rather than assumed, since Digger's own
// upstream `case -1: gb.titleScreen(...); break;` only makes sense once you
// know what makes `gb.menu()` actually return -1: real `Buttons::pressed
// (BTN_B) || pressed(BTN_C)` cancels (plays Cancel, returns -1); only
// `BTN_A` confirms (returns the highlighted item, plays OK). Crucially,
// canceling out of the menu this way does **not** return to gameplay - it
// shows the "DIGGER" title screen (blocking on a fresh A-press), and once
// dismissed, `gamestate` is *still* PAUSED, so the very next tick opens the
// pause menu again from scratch (cursor reset to item 0, matching real
// `gb.menu()`'s own fresh `activeItem = 0` on every new call) - a real,
// slightly odd, upstream round-trip (cancel -> title -> menu again, never
// straight back to gameplay) preserved exactly via `digMenuTitleActive`.
// Only the real "Resume" menu item (index 1) or another action item (New
// Game/Load/Level up/Level down/Toggle Mode, each of which explicitly sets
// `gamestate = RUNNING` in its own real case body) actually returns to
// gameplay. The real widget's own slide-in/out animation is not
// reproduced - cosmetic only, no gameplay effect, matching this project's
// own "no real per-pixel layout to restore" norm for every hand-rolled menu
// screen so far.
//
// -----------------------------------------------------------------------------
// Real upstream quirks found - preserve real bugs by default is this
// project's own explicit, repeated policy, but #2 below was fixed on direct
// request once flagged as genuinely negative for player experience (not
// just a curiosity), the same exception this project has already made for
// a handful of other games' own worst offenders.
// -----------------------------------------------------------------------------
//
// 1) **A real "missing parentheses" bug in `loadEEPROM()`**: upstream
//    writes `cleanEEPROM;` (a bare function reference, not a call -
//    legal-but-useless C++, silently does nothing) instead of
//    `cleanEEPROM();` on a fresh/corrupted-signature EEPROM. This means
//    `cleanEEPROM()` is **real, but 100% dead code** - it is never actually
//    invoked from anywhere in the entire game. Reproduced here by simply
//    never calling `digCleanEEPROM()` from `digLoadEEPROM()` either (the
//    function itself is still ported, for source fidelity, just as
//    genuinely unreachable as upstream's own copy) - not reproducing the
//    literal `digCleanEEPROM;` no-op statement itself, since a bare
//    function-name expression statement is untested/unnecessary syntax
//    this dialect has no proven need for; omitting the call achieves the
//    identical real-world effect.
// 2) **FIXED - was: `GAMEOVER` never called `initWorld()`**: every other
//    case that changes `curLevel`/game progress (New Game, Load, Level
//    up/down, Toggle Mode) explicitly calls `initWorld(curLevel)` afterward
//    - the real `case GAMEOVER: newGame(); dead=false; gamestate=RUNNING;
//    break;` conspicuously did not, so after running out of lives the
//    player's score/lives/level counters reset to a fresh game but gameplay
//    resumed on whatever half-dug board was left over from the run that
//    just ended, until the next real level transition. Fixed in
//    `digUpdateGameover()`, which now calls `digInitWorld(digCurLevel)`
//    after `digNewGame()`, matching every other progress-changing state.
//    Also real: this state draws nothing at all, so - since
//    `gbUpdate()` clears the framebuffer every tick regardless - the
//    transition tick renders one real blank white frame.
// 3) **`NUM_LEVELS` is 152, but the real `levels[]` pointer table upstream
//    only has 151 real initializers** (confirmed directly by parsing
//    `Level.h` - 151 real distinct level names are listed, not 152, one of
//    which - `level80` - even appears out of numeric order at the very
//    end, right before the bonus `theend`/`gameover` entries). A real C/C++
//    array declared `const byte* levels[152] = { /* 151 items */ };`
//    implicitly zero-fills the one remaining slot - `levels[151]` is a real
//    **null pointer** on upstream. `nextLevel()`'s own real bound
//    (`curLevel < NUM_LEVELS-3`, i.e. capped at 149) keeps normal play from
//    ever reaching index 151 through the level-up path - but
//    `loadEEPROM()` reads `cureasy`/`curhard` (and thus `curLevel`)
//    directly from raw EEPROM bytes with **zero range validation**, so a
//    corrupted or fresh/erased (0xFF=255) memory card could set `curLevel`
//    to any value 0-255, including 151 (dereferencing that real null
//    pointer) or anything above 151 (reading arbitrarily far past the real
//    array's own bounds) - a second, more severe, unguarded EEPROM-
//    validation gap than the one `lives > LIVES` explicitly guards against.
//    `digGetLevelData()`'s own if-chain has no way to reproduce an actual
//    wild/null pointer dereference (there is no equivalent "uninitialized
//    flash address" to alias into here, and doing so would just crash this
//    port for no representative benefit) - it falls back to the last real
//    entry (the "gameover" screen) for any out-of-range index instead, a
//    deliberate safety net for this specific unreachable-in-normal-play
//    edge case, not a change to any real, exercised gameplay logic (which
//    still caps at 149 exactly like upstream).
// 4) **A real out-of-bounds column-major array alias, made safe here
//    instead of reproduced literally.** `falling()`'s own real ROCK-on-
//    CHANGER check reads `world[x][y+2]` at the last row `updatePhysics()`
//    ever processes (`y == WORLD_H-2 == 12`), where `y+2 == 14` is one past
//    upstream's own real `WORLD_H` (14, valid indices 0-13). On real
//    hardware's column-major `byte world[WORLD_W][WORLD_H]` layout, this
//    silently aliases into `world[x+1][0]` (the *next column's* row-0 cell)
//    - always a border WALL tile in practice, so the guarded branch is
//    reachable-in-theory but WALL != EMPTY makes it fire essentially never
//    at that specific row. This port's own **row-major** flattening
//    (`digWorldGet`/`digWorldSet`, `y*DIG_WORLD_W+x`) would instead compute
//    a genuinely out-of-bounds index into `digWorld[280]` at that same
//    call site (writing past the end of the array, corrupting whatever
//    global happens to be declared next) - a real memory-safety risk this
//    port's own different (if equally real-hardware-accurate) array layout
//    would introduce that upstream's own layout never actually hit.
//    Guarded explicitly (`y + 2 < DIG_WORLD_H`) in `digFalling()` below to
//    reproduce the same practically-unreachable real-hardware *outcome*
//    (that branch essentially never fires at the last row) without the
//    actual undefined-behavior risk - not a gameplay-visible change from
//    real hardware, just a safe reproduction of it.
// 5) **The pause menu's own real "Save" costs a life** (`case 3: if (lives
//    > 0) { lives--; saveEEPROM(); ... }`) - a genuine, deliberate-looking
//    upstream design choice (saving costs one life, presumably to
//    discourage save-scumming), preserved exactly in `digMenuExecute(3)`.
// 6) `digLives` is a plain `int`, not a wraparound-capable byte (this
//    dialect has no distinct byte type anyway - see avrCompat.h). Confirmed
//    this changes nothing: `lives` only ever decreases during play (`die()`
//    /the Save menu item), and the RUNNING-state check that ends the game
//    (`lives < 1 || lives > LIVES`) already catches the exact tick `lives`
//    reaches 0 before any wraparound could matter - the `> LIVES` half of
//    that check exists specifically to catch a corrupted/fresh (0xFF=255)
//    EEPROM `lives` byte loaded directly via `loadEEPROM()`, not a decrement
//    underflow (no code path anywhere in this source ever increments
//    `lives`).
//
// -----------------------------------------------------------------------------
// Bitmap/mask check (per this project's own established bug class)
// -----------------------------------------------------------------------------
// Every one of the 17 real, reachable sprites in `sprites.h` is a single,
// fully self-contained solid 6x6 glyph (`{8, 6, b0..b5}`) - upstream never
// draws a separate fill/mask layer underneath any of them (unlike
// FlappyBirdo's pipes/bird or Parachute's canopy, which this project's own
// CLAUDE.md documents as a real, previously-found bug class) - confirmed by
// reading `sprites.h` and every `gb.display.drawBitmap()` call site in
// `Render.ino` directly. No mask/fill restoration was needed here.
//
// -----------------------------------------------------------------------------
// Frame-pacing counter
// -----------------------------------------------------------------------------
// Real upstream `gb.frameCount` drives three real pacing checks: monster
// movement throttled to every 10th tick, gravity/physics throttled to every
// 5th tick, and the diamond sprite's own blink animation on odd ticks. Ported
// here as the shim's own `gbFrameCount` global (incremented once per real
// logic tick inside `gbUpdate()`, matching real hardware's own placement).

