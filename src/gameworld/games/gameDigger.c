void digFalling( int x, int y, int sprite )
{
    int below;

    if( ( digWorldGet( x, y ) & DIG_FALLINGSTATE ) > 0 )
    {
        below = digWorldGet( x, y + 1 ) & DIG_SPRITEMASK;
        if( below == DIG_PLAYER ) { digDie(); return; }
        if( below == DIG_MONSTER_D || below == DIG_MONSTER_U || below == DIG_MONSTER_L || below == DIG_MONSTER_R )
        {
            digMonsterDie( x, y + 1 );
            return;
        }
    }

    digWorldSet( x, y, digWorldGet( x, y ) & ~DIG_FALLINGSTATE );

    if( digWorldGet( x, y + 1 ) == DIG_EMPTY )
    {
        digWorldSet( x, y + 1, sprite );
        digWorldSet( x, y, DIG_EMPTY );
        digWorldSet( x, y + 1, digWorldGet( x, y + 1 ) | DIG_FALLINGSTATE );
        return;
    }

    if( digWorldGet( x, y + 1 ) == DIG_ROCK || digWorldGet( x, y + 1 ) == DIG_DIAMOND )
    {
        if( digWorldGet( x + 1, y + 1 ) == DIG_EMPTY && digWorldGet( x + 1, y ) == DIG_EMPTY )
        {
            digWorldSet( x + 1, y + 1, sprite );
            digWorldSet( x, y, DIG_EMPTY );
        }
        else if( digWorldGet( x - 1, y + 1 ) == DIG_EMPTY && digWorldGet( x - 1, y ) == DIG_EMPTY )
        {
            digWorldSet( x - 1, y + 1, sprite );
            digWorldSet( x, y, DIG_EMPTY );
        }
        return;
    }

    // Real upstream reads `world[x][y+2]` here, which - only at the very
    // last row this loop ever processes - is one past real hardware's own
    // WORLD_H (14). See header comment #5: guarded here to reproduce the
    // same practically-unreachable real-hardware outcome without this
    // port's own row-major flattening turning it into an actual
    // out-of-bounds array write.
    if( sprite == DIG_ROCK && y + 2 < DIG_WORLD_H && digWorldGet( x, y + 1 ) == DIG_CHANGER && digWorldGet( x, y + 2 ) == DIG_EMPTY )
    {
        digWorldSet( x, y, DIG_EMPTY );
        digWorldSet( x, y + 2, DIG_DIAMOND | DIG_FALLINGSTATE );
    }
}

void digMoveRock( int xoff, int yoff )
{
    xoff = xoff; // unused - real upstream's own moveRock(xoff,yoff) never reads xoff either
    if( yoff != 0 )
    {
        gbPlayTick();
        return;
    }
    if( gbHeld( BTN_RIGHT, 8 ) && digWorldGet( digCursorX + 2, digCursorY ) == DIG_EMPTY )
    {
        digWorldSet( digCursorX + 2, digCursorY, DIG_ROCK );
        digMovePlayer( 1, 0 );
        gbPlayCancel();
    }
    if( gbHeld( BTN_LEFT, 8 ) && digWorldGet( digCursorX - 2, digCursorY ) == DIG_EMPTY )
    {
        digWorldSet( digCursorX - 2, digCursorY, DIG_ROCK );
        digMovePlayer( -1, 0 );
        gbPlayCancel();
    }
}

void digUpdatePhysics()
{
    int x;
    int y;
    int sprite;

    if( ( gbFrameCount % 5 ) == 0 )
    {
        for( y = DIG_WORLD_H - 2; y > 0; y = y - 1 )
        {
            for( x = 1; x < DIG_WORLD_W - 1; x = x + 1 )
            {
                sprite = digWorldGet( x, y ) & ~DIG_FALLINGSTATE & ~DIG_TYPEMASK;
                if( sprite == DIG_ROCK ) digFalling( x, y, DIG_ROCK );
                else if( sprite == DIG_DIAMOND ) digFalling( x, y, DIG_DIAMOND );
                else if( sprite == DIG_MONSTER_D ) digMoveMonster( x, y, DIG_MONSTER_D );
                else if( sprite == DIG_MONSTER_U ) digMoveMonster( x, y, DIG_MONSTER_U );
                else if( sprite == DIG_MONSTER_L ) digMoveMonster( x, y, DIG_MONSTER_L );
                else if( sprite == DIG_MONSTER_R ) digMoveMonster( x, y, DIG_MONSTER_R );
            }
        }
        for( y = DIG_WORLD_H - 2; y > 0; y = y - 1 )
        {
            for( x = 1; x < DIG_WORLD_W - 1; x = x + 1 )
            {
                digWorldSet( x, y, digWorldGet( x, y ) & ~DIG_MOVINGSTATE );
            }
        }
    }
}

// -----------------------------------------------------------------------------
// Player.ino (continued)
// -----------------------------------------------------------------------------

void digHandlePlayer( int xoff, int yoff )
{
    int target;

    digDir = 7 + xoff * 2 + yoff;
    digTimer = 5;
    target = digWorldGet( digCursorX + xoff, digCursorY + yoff ) & ~DIG_FALLINGSTATE;

    if( target == DIG_EMPTY ) digMovePlayer( xoff, yoff );
    else if( target == DIG_WALL ) gbPlayTick();
    else if( target == DIG_ROCK ) digMoveRock( xoff, yoff );
    else if( target == DIG_SOIL ) digMovePlayer( xoff, yoff );
    else if( target == DIG_DIAMOND )
    {
        digMovePlayer( xoff, yoff );
        digDiamonds = digDiamonds + 1;
        gbPlayOK();
    }
    else if( target == DIG_CHANGER ) gbPlayTick();
    else if( target == DIG_DOOR )
    {
        if( digDiamsNeed <= digDiamonds )
        {
            digMovePlayer( xoff, yoff );
            gbPlayOK();
            digNextLevel();
        }
        else gbPlayTick();
    }
    else digDie(); // monsters, or the player tile itself (shouldn't happen)
}

void digUpdateCursor()
{
    int cameraXTarget;
    int cameraYTarget;

    if( gbRepeat( BTN_A, 4 ) && !digDead )
    {
        gbPlayOK();
        digDie();
    }

    if( gbRepeat( BTN_B, 4 ) && digDead )
    {
        gbPlayCancel();
        digInitWorld( digCurLevel );
        digDead = false;
    }

    if( !digDead )
    {
        if( gbRepeat( BTN_RIGHT, 4 ) ) digHandlePlayer( 1, 0 );
        if( gbRepeat( BTN_LEFT, 4 ) ) digHandlePlayer( -1, 0 );
        if( gbRepeat( BTN_DOWN, 4 ) ) digHandlePlayer( 0, 1 );
        if( gbRepeat( BTN_UP, 4 ) ) digHandlePlayer( 0, -1 );
    }

    // target position of the camera for the cursor to be centered, applied
    // with some smoothing
    cameraXTarget = digCursorX * DIG_SPRITE_W - LCDWIDTH / 2 + 3;
    cameraYTarget = digCursorY * DIG_SPRITE_H - LCDHEIGHT / 2 + 3;
    digCameraX = ( digCameraX * 3 + cameraXTarget ) / 4;
    digCameraY = ( digCameraY * 3 + cameraYTarget ) / 4;
}

// -----------------------------------------------------------------------------
// Render.ino
// -----------------------------------------------------------------------------

void digDrawWorld()
{
    int x;
    int y;
    int xScreen;
    int yScreen;
    int sprite;

    for( y = 0; y < DIG_WORLD_H; y = y + 1 )
    {
        for( x = 0; x < DIG_WORLD_W; x = x + 1 )
        {
            xScreen = x * DIG_SPRITE_W - digCameraX;
            yScreen = y * DIG_SPRITE_H - digCameraY;
            sprite = digWorldGet( x, y ) & DIG_SPRITEMASK;

            if( sprite == DIG_DIAMOND && ( gbFrameCount % 2 ) ) sprite = DIG_DIAMOND2;
            if( sprite == DIG_PLAYER ) sprite = DIG_PLAYER + digDir;

            if( xScreen < -DIG_SPRITE_W || xScreen > LCDWIDTH || yScreen < 0 || yScreen > LCDHEIGHT )
              continue; // don't draw sprites which are out of the screen

            gbDrawBitmap( xScreen, yScreen, digGetSpriteBitmap( sprite ) );
        }
    }

    if( digTimer == 0 ) digDir = 7;
    digTimer = digTimer - 1;

    if( digGamemode ) gbSetColor( 1 ); else gbSetColor( 0 );
    gbFillRect( 0, 0, LCDWIDTH, DIG_SPRITE_H );
    if( digGamemode ) gbSetColor( 0 ); else gbSetColor( 1 );

    gbCursorX = 0;
    gbCursorY = 0;
    gbPrintString( digDiamondIconStr );
    gbPrintNumber( digDiamonds );
    gbPrintString( "/" );
    gbPrintNumber( digDiamsNeed );
    gbPrintString( digLivesIconStr );
    gbPrintNumber( digLives );
    gbPrintString( " L:" );
    gbPrintNumber( digCurLevel + 1 );
}

// -----------------------------------------------------------------------------
// EEPROM persistence (Digger.ino) - real upstream addresses 0-9 unchanged,
// this shim's own EEPROM slot is a real, full 1024 bytes (matching real
// ATmega328 hardware) so no address needed truncating. Byte offset 7 is a
// real, unexplained gap upstream never writes/reads either - preserved
// as-is, not "fixed". See header comment #2 for why digCleanEEPROM() below
// is real, ported, but genuinely dead code (never actually called).
// -----------------------------------------------------------------------------

void digCleanEEPROM()
{
    int i;
    for( i = 0; i < 1024; i = i + 1 )
    {
        if( eeprom_read_byte( i ) )
          eeprom_write_byte( i, 0 );
    }
}

void digLoadEEPROM()
{
    if( eeprom_read_byte( 0 ) != DIG_EEPROMTOKEN1 || eeprom_read_byte( 1 ) != DIG_EEPROMTOKEN2 || eeprom_read_byte( 2 ) != DIG_EEPROMTOKEN3 )
    {
        // Real upstream's own `cleanEEPROM;` (missing parens) never
        // actually calls cleanEEPROM() here either - see header comment #2.
        return;
    }

    digGamemode = eeprom_read_byte( 3 );
    digCureasy  = eeprom_read_byte( 4 );
    digMaxeasy  = eeprom_read_byte( 5 );
    digLives    = eeprom_read_byte( 6 );
    digCurhard  = eeprom_read_byte( 8 );
    digMaxhard  = eeprom_read_byte( 9 );
    digMaxeasy  = gbMax( digMaxeasy, digCureasy );
    digMaxhard  = gbMax( digMaxhard, digCurhard );

    if( digGamemode == DIG_EASY ) digCurLevel = digCureasy; else digCurLevel = digCurhard;
    if( digGamemode == DIG_EASY ) digMaxlevel = digMaxeasy; else digMaxlevel = digMaxhard;
}

void digSaveEEPROM()
{
    eeprom_write_byte( 0, DIG_EEPROMTOKEN1 );
    eeprom_write_byte( 1, DIG_EEPROMTOKEN2 );
    eeprom_write_byte( 2, DIG_EEPROMTOKEN3 );
    eeprom_write_byte( 3, digGamemode );
    eeprom_write_byte( 4, digCureasy );
    eeprom_write_byte( 5, digMaxeasy );
    eeprom_write_byte( 6, digLives );
    eeprom_write_byte( 8, digCurhard );
    eeprom_write_byte( 9, digMaxhard );
}

// -----------------------------------------------------------------------------
// Digger.ino (top-level state machine) - see header comment for the full
// reasoning behind every one of these states/transitions.
// -----------------------------------------------------------------------------

void digNewGame()
{
    digCurLevel = 0;
    digLives = DIG_LIVES;
    digMaxeasy = 0;
    digCureasy = 0;
    digMaxhard = 0;
    digCurhard = 0;
    digGamestate = DIG_RUNNING;
    digDead = false;
}

// Real upstream's own `case GAMEOVER` body redundantly re-sets `dead=false`/
// `gamestate=RUNNING` right after calling `newGame()`, which already just
// set both of those exact fields - elided here as inert.
//
// Fixed: real upstream never calls `initWorld()` here (see header comment
// #2), so after running out of lives the score/lives/level reset to a
// fresh game but gameplay resumed on whatever half-dug board was left
// over from the run that just ended - a player-visible bug, not preserved.
// `digInitWorld()` now runs after the reset, matching every other state
// transition that changes `digCurLevel`/progress (New Game, Load, Level
// up/down, Toggle Mode).
void digUpdateGameover()
{
    digNewGame();
    digInitWorld( digCurLevel );
}

void digDrawTitleScreen()
{
    // Upstream's own real `gb.titleScreen()` widget draws a generic logo/
    // name/button-hint screen with no per-pixel data to restore here - a
    // simple centered two-line replacement, matching every other ported
    // game's own title-screen convention (e.g. gamePong.c). Upstream never
    // calls setFont() anywhere in Digger's own source, so this stays on
    // the shim's own real default font3x5 - no gbSetFont() call needed.
    gbSetColor( 1 );
    gbCursorX = 30;
    gbCursorY = 14;
    gbPrintString( "DIGGER" );
    gbCursorX = 28;
    gbCursorY = 26;
    gbPrintString( "PRESS A" );
}

char* digMenuItemText( int idx )
{
    if( idx == 0 ) return "New Game";
    if( idx == 1 ) return "Resume";
    if( idx == 2 ) return "Load";
    if( idx == 3 ) return "Save";
    if( idx == 4 ) return "Level up";
    if( idx == 5 ) return "Level down";
    return "Toggle Mode"; // idx == 6
}

void digDrawMenuList()
{
    int i;
    int y;

    gbSetColor( 1 );

    for( i = 0; i < DIG_MENULENGTH; i = i + 1 )
    {
        y = i * gbFontHeight;
        gbCursorX = 7;
        gbCursorY = y;
        gbPrintString( digMenuItemText( i ) );

        if( i == digMenuCursor )
        {
            gbCursorX = 1;
            gbCursorY = y;
            gbPrintString( ">" );
        }
    }
}

// Direct equivalent of upstream's own real `switch (gb.menu(menu,
// MENULENGTH))` case bodies (cases 0-6 - the real -1/"nothing selected"
// case is handled separately via digMenuTitleActive, see header comment).
void digMenuExecute( int idx )
{
    if( idx == 0 ) // New Game
    {
        digNewGame();
        digInitWorld( digCurLevel );
    }
    else if( idx == 1 ) // Resume
    {
        digGamestate = DIG_RUNNING;
    }
    else if( idx == 2 ) // Load
    {
        digLoadEEPROM();
        digGamestate = DIG_RUNNING;
        digDead = false;
        digInitWorld( digCurLevel );
    }
    else if( idx == 3 ) // Save - see header comment #6, this really does cost a life
    {
        if( digLives > 0 )
        {
            digLives = digLives - 1;
            digSaveEEPROM();
            digGamestate = DIG_RUNNING;
            digDead = false;
        }
    }
    else if( idx == 4 ) // Level up
    {
        digGamestate = DIG_RUNNING;
        digDead = false;
        if( digGamemode == DIG_EASY )
        {
            if( digCurLevel < digMaxeasy ) digNextLevel();
        }
        else
        {
            if( digCurLevel < digMaxhard ) digNextLevel();
        }
    }
    else if( idx == 5 ) // Level down
    {
        if( digCurLevel > 0 )
        {
            if( digGamemode == DIG_EASY ) digCureasy = digCureasy - 1;
            else digCurhard = digCurhard - 1;
            digCurLevel = digCurLevel - 1;
        }
        digDead = false;
        digGamestate = DIG_RUNNING;
        digInitWorld( digCurLevel );
    }
    else // idx == 6, Toggle Mode
    {
        digGamemode = !digGamemode;
        if( digGamemode == DIG_EASY ) digCurLevel = digCureasy; else digCurLevel = digCurhard;
        digDead = false;
        digInitWorld( digCurLevel );
        digGamestate = DIG_RUNNING;
    }
}

void digUpdateMenu()
{
    bool exiting;

    if( digMenuTitleActive )
    {
        digDrawTitleScreen();
        if( gbPressed( BTN_A ) )
        {
            digMenuTitleActive = false;
            digMenuCursor = 0;
        }
        return;
    }

    digDrawMenuList();

    exiting = false;

    if( gbPressed( BTN_A ) )
    {
        exiting = true;
        gbPlayOK();
        digMenuExecute( digMenuCursor );
    }
    else if( gbPressed( BTN_B ) || gbPressed( BTN_C ) )
    {
        exiting = true;
        gbPlayCancel();
        digMenuTitleActive = true;
    }

    if( !exiting )
    {
        if( gbRepeat( BTN_DOWN, 4 ) )
        {
            digMenuCursor = digMenuCursor + 1;
            if( digMenuCursor >= DIG_MENULENGTH ) digMenuCursor = 0;
            gbPlayTick();
        }
        if( gbRepeat( BTN_UP, 4 ) )
        {
            digMenuCursor = digMenuCursor - 1;
            if( digMenuCursor < 0 ) digMenuCursor = DIG_MENULENGTH - 1;
            gbPlayTick();
        }
    }
}

void digUpdateRunning()
{
    // Real upstream keeps running gameplay this exact same tick even after
    // flagging PAUSED (the switch to the menu only visibly takes effect
    // next tick) - preserved exactly, no early return here.
    if( gbPressed( BTN_C ) )
    {
        digGamestate = DIG_PAUSED;
        digMenuTitleActive = false;
        digMenuCursor = 0;
    }

    digUpdateCursor();
    digUpdatePhysics();
    digDrawWorld();

    if( digLives < 1 || digLives > DIG_LIVES )
      digGamestate = DIG_GAMEOVER;
}

void digUpdateTitleBoot()
{
    digDrawTitleScreen();
    if( gbPressed( BTN_A ) )
    {
        digLoadEEPROM();
        digInitWorld( digCurLevel );
        digGamestate = DIG_RUNNING;
        digState = DIG_STATE_PLAY;
    }
}

void gameDigger_init()
{
    gbBegin();
    digState = DIG_STATE_TITLE;
    digGamestate = DIG_RUNNING;
    digMenuCursor = 0;
    digMenuTitleActive = false;
}

void gameDigger_update()
{
    if( !gbUpdate() ) return;


    if( digState == DIG_STATE_TITLE ) digUpdateTitleBoot();
    else if( digGamestate == DIG_PAUSED ) digUpdateMenu();
    else if( digGamestate == DIG_GAMEOVER ) digUpdateGameover();
    else digUpdateRunning();

    gbRenderFrame();
}
