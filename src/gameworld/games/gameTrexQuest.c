void trexUpdatePlay()
{
    gbSetColor( 1 ); // BLACK - see header comment on the cross-tick color-state normalization

    // real upstream's own 3-tile scrolling background/foreground bands
    gbDrawBitmap( trexScrolling, 8, trexHorizon1Bitmap );
    gbDrawBitmap( trexScrolling + LCDWIDTH, 8, trexHorizon1Bitmap );
    gbDrawBitmap( trexScrolling - LCDWIDTH, 8, trexHorizon1Bitmap );

    gbDrawBitmap( trexScrolling2, 30, trexHorizon3Bitmap );
    gbDrawBitmap( trexScrolling2 + LCDWIDTH, 30, trexHorizon3Bitmap );
    gbDrawBitmap( trexScrolling2 - LCDWIDTH, 30, trexHorizon3Bitmap );

    // slow decorative car - erase its old footprint (a real, undersized
    // upstream erase rect - 24x9 even though car sprites can be up to 14
    // tall - preserved exactly, not corrected) then redraw it
    gbSetColor( 0 );
    gbFillRect( trexScrolling2 + LCDWIDTH + 5 + 1, trexCarY + 1, 24, 9 );
    gbSetColor( 1 );
    gbDrawBitmap( trexScrolling2 + LCDWIDTH + 5, trexCarY, trexCars[ trexCarState ] );

    // re-init scrolling wraparound (both exact-equality checks are real and
    // safe here: Scrolling/Scrolling2 only ever change by exactly +-1/+-2
    // per tick from an even starting point, so they pass through every
    // reachable value on the way, never skip past it)
    if( trexScrolling2 == ( -2 * LCDWIDTH ) )
    {
        trexScrolling2 = 0;
        trexCarY = 32 + arand( LCDHEIGHT - 4 - 32 );
        trexPomX = 10 + arand( LCDWIDTH - 10 );
        trexPomY = 20 + arand( LCDHEIGHT - 15 - 20 );
        trexCarState = arand( 4 );
    }
    if( trexScrolling == ( -2 * LCDWIDTH ) )
      trexScrolling = 0;

    if( trexBarreDeVie <= 59 )
    {
        // real upstream "exit game" - a full Button-C restart, converted
        // into this project's own real "blocking title screen -> explicit
        // state" treatment (see gamePong.c's own header comment): reset the
        // real restart-scope globals and return straight to the title
        // state, matching upstream's own real `setup()` call exactly.
        if( gbPressed( BTN_C ) )
        {
            trexBeginTitle();
            return;
        }

        // field / power bar / life bar
        gbDrawLine( 0, 18, LCDWIDTH, 18 );

        gbDrawRect( LCDWIDTH - 30, 2, 20, 3 );
        gbDrawLine( LCDWIDTH - 30, 3, LCDWIDTH - trexPuissance, 3 );

        gbDrawRect( LCDWIDTH - 60, 2, 20, 3 );
        gbDrawLine( LCDWIDTH - 60, 3, LCDWIDTH - trexBarreDeVie, 3 );

        // score readout
        gbCursorX = 1;
        gbCursorY = 0;
        gbPrintNumber( trexScore );

        // apple or chily
        if( trexChilyRand == 5 )
          gbDrawBitmap( trexPomX, trexPomY, trexChilyBitmap );
        else
          gbDrawBitmap( trexPomX, trexPomY, trexPomBitmap );

        // tank + HUD icons
        gbDrawBitmapRotated( trexTankX, trexTankY, trexTanks[ trexTankState ], 0, 1 ); // NOROT, FLIPH
        gbDrawBitmap( LCDWIDTH - 69, 0, trexHeartBitmap );
        gbDrawBitmap( LCDWIDTH - 39, 0, trexMinipomBitmap );

        // TREX - erase its own mouth area (real upstream WHITE fillRect)
        // before drawing the current directional sprite
        gbSetColor( 0 );
        if( ( trexDirec == 0 ) || ( trexDirec == 2 ) ) // facing right
          gbFillRect( trexX + 7, trexY, 5, 3 );
        if( ( trexDirec == 1 ) || ( trexDirec == 3 ) ) // facing left
          gbFillRect( trexX + 3, trexY, 5, 3 );
        gbSetColor( 1 );
        gbDrawBitmap( trexX, trexY, trexSprites[ trexDirec ] );

        trexExplode = 0;

        // ------- Controls ----------------------------------------------

        if( gbRepeat( BTN_RIGHT, 1 ) )
        {
            trexScrolling = trexScrolling - 1;
            trexScrolling2 = trexScrolling2 - 2;
            trexTankX = trexTankX - 1;
            trexPomX = trexPomX - 1;
            if( trexX < ( LCDWIDTH - 25 ) )
              trexX = trexX + 1;
            trexDirec = trexDirec + 2;
            if( trexDirec > 2 )
              trexDirec = 0;
        }
        if( gbRepeat( BTN_LEFT, 1 ) )
        {
            trexScrolling = trexScrolling + 1;
            trexScrolling2 = trexScrolling2 + 2;
            trexTankX = trexTankX + 1;
            trexPomX = trexPomX + 1;
            if( trexX > 0 )
              trexX = trexX - 1;
            trexDirec = trexDirec + 2;
            if( trexDirec > 3 )
              trexDirec = 1;
        }
        if( gbRepeat( BTN_DOWN, 1 ) )
        {
            if( trexY < ( LCDHEIGHT - 8 ) )
              trexY = trexY + 1;
        }
        if( gbRepeat( BTN_UP, 1 ) )
        {
            if( trexY > 6 )
              trexY = trexY - 1;
        }

        if( gbRepeat( BTN_A, 1 ) )
        {
            // real upstream `puissance++;puissance++;puissance--;` - see
            // header comment: nets out to a plain +1 every time, ported as such.
            if( trexPuissance < 30 )
              trexPuissance = trexPuissance + 1;

            // draw right-facing fire/ray
            if( ( trexDirec == 0 ) || ( trexDirec == 2 ) )
            {
                if( trexPuissance < 29 )
                {
                    if( trexActivateRay == 0 )
                      gbDrawBitmap( trexX + 17, trexY, trexFire[ trexStateFire ] );
                    if( trexActivateRay == 1 )
                      gbDrawBitmapRotated( trexX + 10, trexY - 4, trexRayBitmap, 0, 1 ); // NOROT, FLIPH
                }
                trexStateFire = trexStateFire + 1;
                if( trexStateFire > 2 )
                  trexStateFire = 0;
            }

            // draw left-facing fire/ray (real upstream asymmetry preserved:
            // this branch's own puissance threshold is < 30, not < 29 like
            // the right-facing branch above)
            if( ( trexDirec == 1 ) || ( trexDirec == 3 ) )
            {
                if( trexPuissance < 30 )
                {
                    if( trexActivateRay == 1 )
                      gbDrawBitmap( trexX - 81, trexY - 4, trexRayBitmap );
                    if( trexActivateRay == 0 )
                      gbDrawBitmapRotated( trexX - 17, trexY, trexFire[ trexStateFire ], 0, 1 ); // NOROT, FLIPH
                }
                trexStateFire = trexStateFire + 1;
                if( trexStateFire > 2 )
                  trexStateFire = 0;
            }
        }

        // when TREX touches the apple (real upstream quirk preserved: this
        // always hit-tests against the apple's own real shape, even on the
        // real ticks a chily is the one actually drawn - see header comment)
        if( gbCollideBitmapBitmap( trexX, trexY, trexSprites[ trexDirec ], trexPomX, trexPomY, trexPomBitmap ) )
        {
            trexScore = trexScore + 5;
            trexPomX = 10 + arand( LCDWIDTH - 10 );
            trexPomY = 20 + arand( LCDHEIGHT - 15 - 20 );

            if( trexChilyRand == 5 )
            {
                trexActivateRay = 1; // chily eaten - activate the ray
                trexRayOrFireHitBox = 88; // and widen the fire hitbox to match
                trexPuissance = 11; // power bar refilled by the chily
            }
            if( trexChilyRand != 5 )
            {
                trexActivateRay = 0; // plain apple - no ray
                trexRayOrFireHitBox = 16;
            }

            trexChilyRand = 1 + arand( 9 ); // real 1/9 chance of a 5 - see header comment on the "1/10" comment discrepancy
            if( trexPuissance > 11 )
            {
                trexPuissance = trexPuissance - 4;
                if( trexPuissance < 11 )
                  trexPuissance = 11;
            }
        }

        // when TREX touches the "car" hitbox - real upstream bug preserved:
        // this pairs the TANK's own x with the separate CAR's own y (see
        // header comment)
        if( gbCollideRectRect( trexX, trexY, 16, 2, trexTankX, trexCarY, 8, 2 ) )
        {
            if( trexBarreDeVie < 60 )
              trexBarreDeVie = trexBarreDeVie + 1;
        }

        // when TREX touches the real TANK hitbox
        if( gbCollideRectRect( trexX, trexY, 16, 2, trexTankX, trexTankY, 16, 2 ) )
        {
            if( trexBarreDeVie < 60 )
              trexBarreDeVie = trexBarreDeVie + 1;
        }

        // when TREX burns the tank with fire/ray
        if( gbRepeat( BTN_A, 1 ) )
        {
            if( trexPuissance < 30 )
            {
                if( gbCollideRectRect( trexX + 17, trexY + 16, trexRayOrFireHitBox, 2, trexTankX, trexTankY + 16, 16, 2 ) )
                {
                    if( ( trexDirec == 0 ) || ( trexDirec == 2 ) ) // TREX facing right
                    {
                        trexExplode = 1;
                        trexTankState = 3;
                        trexTankX = -16;
                        trexTankY = 10 + arand( LCDHEIGHT - 10 - 10 );
                        trexScore = trexScore + 10;
                    }
                }
                if( gbCollideRectRect( trexX - 17, trexY + 16, trexRayOrFireHitBox, 2, trexTankX, trexTankY + 16, 16, 2 ) )
                {
                    if( ( trexDirec == 1 ) || ( trexDirec == 3 ) ) // TREX facing left
                    {
                        trexExplode = 1;
                        trexTankState = 3;
                        trexTankX = -16;
                        trexTankY = 10 + arand( LCDHEIGHT - 10 - 10 );
                        trexScore = trexScore + 10;
                    }
                }
            }
        }

        if( trexExplode < 1 )
        {
            if( trexTankX > -16 )
              trexTankX = trexTankX - ( 1 * trexSpeedUp );
            if( trexTankX < -16 )
            {
                trexTankX = LCDWIDTH + 16;
                trexTankY = 10 + arand( LCDHEIGHT - 10 - 10 );
            }
            trexTankState = trexTankState + 1;
            if( trexTankState > 1 )
              trexTankState = 0;
        }
    } // end trexBarreDeVie <= 59

    // --- when TREX walks on the slow decorative car (real upstream check,
    // unconditional every tick regardless of trexBarreDeVie) ---
    if( gbCollideBitmapBitmap( trexX, trexY, trexSprites[ trexDirec ], trexScrolling2 + LCDWIDTH + 5, trexCarY, trexCars[ trexCarState ] ) )
    {
        gbDrawBitmap( trexScrolling2 + LCDWIDTH + 5, trexCarY, trexCarExplodeBitmap );
        trexCarY = LCDHEIGHT + 20;
    }

    // GAME OVER (real upstream check, unconditional every tick)
    if( trexBarreDeVie > 59 )
    {
        gbClear();
        gbSetColor( 1 );
        gbCursorX = 0; // normalized explicit cursor position - see header comment
        gbCursorY = 0;
        gbPrintString( "Score: " );
        gbPrintNumber( trexScore );
        gbDrawBitmap( 10, 10, trexGameoverBitmap );

        if( gbRepeat( BTN_B, 1 ) )
          trexInitGame();
    }

    // LEVEL UP (real upstream check, unconditional every tick - see header
    // comment for why this can visually overwrite the GAME OVER screen
    // above on the one real tick both conditions are true, preserved on
    // purpose)
    if( trexScore >= ( 100 * trexLevelN ) )
    {
        gbClear();
        gbSetColor( 1 );
        gbCursorX = 0; // normalized explicit cursor position - see header comment
        gbCursorY = 0;
        gbPrintString( "LEVEL: " );
        gbPrintNumber( trexLevelN );
        gbDrawBitmap( 0, 5, trexLogo2Bitmap );

        if( gbRepeat( BTN_B, 1 ) )
        {
            // == upstream NextLevel(): a real leveln/SpeedUp increment -
            // upstream's own version also recurses straight back into
            // loop() here, processing one extra real logic tick
            // immediately rather than waiting for the next real gb.update()
            // tick; this port simply lets the very next real engine tick
            // pick it up instead (see header comment on the state machine
            // for why this whole game intentionally avoids upstream's own
            // recursive loop() re-entry pattern) - harmless, since nothing
            // upstream's own extra recursed tick did depended on running
            // within that exact same real tick.
            trexLevelN = trexLevelN + 1;
            trexSpeedUp = trexSpeedUp + 1;
        }
    }
}

void gameTrexQuest_init()
{
    gbBegin();

    // real one-time-only global initial values - see header comment
    trexX = 10;
    trexY = 10;
    trexPomX = 30;
    trexPomY = 30;
    trexDirec = 0;
    trexCarState = 0;
    trexStateFire = 0;
    trexTankState = 0;
    trexExplode = 0;
    trexChilyRand = 0;
    trexActivateRay = 0;
    trexRayOrFireHitBox = 16;
    trexScrolling = 0;
    trexScrolling2 = 0;

    gbPickRandomSeed();
    trexBeginTitle();
}

void gameTrexQuest_update()
{
    if( !gbUpdate() ) return;

    if( trexState == TREX_STATE_TITLE ) trexUpdateTitle();
    else trexUpdatePlay();

    gbRenderFrame();
}
