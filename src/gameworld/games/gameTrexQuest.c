// TREX QUEST II (Awot83/AWOT, GPLv3 - github.com/Awot83/Gamebuino-TREX-QUEST,
// "made with my son who likes T-Rex"). A T-Rex runs across a scrolling city
// skyline, eats apples (occasionally a chily that grants a temporary
// screen-wide ray weapon) to build up a fire meter, and burns passing tanks
// with its own breath weapon while dodging both the tank and a separate
// slow-moving car for score, health, and level progression.
//
// Single real upstream file (trex_quest.ino, one flat loop()) - no
// multi-file consolidation needed. Every real `gb.x.y(...)` call site was
// mechanically rewritten to a plain `gbY(...)` function call (see
// gamePong.c's own header comment for why - this dialect has no classes/
// methods). `random(min,max)` became `min + arand(max-min)` (this dialect's
// own established RNG helper, matching Arduino's own `[min,max)` semantics
// exactly). `byte` stayed a plain `int` throughout (avrCompat.h aliasing).
//
// REAL BITMAP ART: every real `const byte NAME PROGMEM[] = { width, height,
// ... }` array upstream was copied byte-for-byte (via a small script reading
// trex_quest.ino directly and converting every `B00000000`-style binary
// literal to hex - verified by re-decoding several sprites, including
// trex1/tank1/heart/pom/chily, back into an ASCII preview before trusting
// them, not hand-transcribed) into the `int name[N] = { width, height,
// byte0, ... }` shape gbDrawBitmap()/gbDrawBitmapRotated() expect directly -
// upstream's own header bytes already ARE the width/height pair this shim
// wants, no reshaping needed. `cars[]`/`sprites[]`/`tank[]`/`fire[]` (real
// upstream `const byte* NAME[N]` pointer tables) became real
// `int* name[N] = {...}` arrays - this dialect's own proven array-of-
// bitmap-pointers idiom (see gameUfoRace.c's own `ufoSprites`).
// `trexCar6Bitmap` (upstream's own literal `{2, 2, 0, 0, 0}` "empty car"
// placeholder) is ported with its real 2x2 pixel data only (the extra third
// zero byte upstream provided is dead padding past what a 2x2 bitmap even
// needs - dropped since gbDrawBitmap() never reads it either way) - moot
// regardless, since `carstate` is only ever randomized across indices 0-3
// (`random(0, 4)`), so this 6th, all-blank car sprite is genuinely
// unreachable dead data on real hardware too, not something this port
// disabled.
//
// DEAD CODE NOT PORTED (checked directly against trex_quest.ino, not
// assumed): `horizon2`/`cloud1`/`cloud1b` (declared, never once passed to
// `drawBitmap()` anywhere in `loop()`) and `fireg[]`/`fire0g`/`fire1g`/
// `fire2g` (a whole second, gray-tinted fire sprite set, also declared but
// never referenced - only the plain `fire[]` array is ever drawn). None of
// these are ported.
//
// STATE MACHINE: upstream's own blocking `gb.titleScreen(F(""), logo)`
// (called from `mainMenu()`, itself called once from `setup()`) becomes an
// explicit TREX_STATE_TITLE state, matching the "blocking loop -> explicit
// resumable state" treatment used throughout this project (see gamePong.c's
// own header comment) - dismissed by a real Button A press, matching
// upstream's own real `titleScreen()` contract exactly. The logo is drawn
// directly via `gbDrawBitmap(0, 12, trexLogoBitmap)` - the same real
// `titleScreen()`-internal bitmap anchor point this project already
// confirmed by reading the real `Gamebuino::titleScreen()` source while
// porting gameFlappyBirdo.c (whose own 64-wide title bitmap uses the exact
// same anchor); TREX QUEST's own real `logo` bitmap is also 64 wide and,
// at 36 tall, its own bottom edge (12+36) lands exactly on this real 48px
// screen's own bottom edge - corroborating the same real anchor point
// rather than a guess.
//
// Everything past the title screen is a single TREX_STATE_PLAY state that
// mirrors upstream's own real `loop()` body directly, including its own
// three real UNCONDITIONAL per-tick checks running in upstream's own exact
// order (not converted into separate mutually-exclusive states, since
// upstream itself doesn't treat them that way): the scrolling background/
// car (always drawn), the core "TREX alive" gameplay block (gated on
// `barredevie <= 59`, matching upstream's own real `if` exactly), the TREX-
// walks-on-car explosion check (unconditional), the GAME OVER screen
// (`barredevie > 59`), and the LEVEL UP screen (`score >= 100*leveln`) -
// this last pair are real upstream `if`s, not an `if/else if`, so on the
// one real tick both conditions are simultaneously true (dying exactly on
// a level-up score), upstream's own LEVEL UP screen draws AFTER and
// visually wins over GAME OVER's own already-drawn screen that same tick -
// preserved here for real by keeping the exact same unconditional check
// order, rather than inventing separate GAMEOVER/LEVELUP enum states that
// would have made the two mutually exclusive.
//
// A REAL, DELIBERATELY PRESERVED UPSTREAM QUIRK - "restart" doesn't reset
// everything: upstream's own `initGame()` (called from `setup()` before the
// title screen, from GAME OVER's own Button B, and from `NextLevel()`)
// only resets `barredevie`/`tankx`/`tanky`/`score`/`puissance`/`leveln`/
// `SpeedUp`/`CarY` - it does NOT reset `x`/`y`/`pomx`/`pomy`/`direc`/
// `carstate`/`statefire`/`tankstate`/`explode`/`chilyrand`/`activateRay`/
// `RayOrFireHitBox`/`Scrolling`/`Scrolling2`, which upstream only ever
// initializes ONCE, as real global C++ variable initializers that run
// exactly once at real power-on - never again, not even via a full
// mid-game Button-C restart (`setup()` itself never touches them either).
// So on real hardware, restarting mid-game (Button C) or from GAME OVER
// (Button B) resumes with the TREX's own exact previous position, facing
// direction, walk-cycle frame, apple/chily position and pending type, and
// background scroll offset intact - only health/tank/score/fire-power/
// level genuinely reset. Reproduced exactly: `trexX`/`trexY`/`trexPomX`/
// `trexPomY`/`trexDirec`/`trexCarState`/`trexStateFire`/`trexTankState`/
// `trexExplode`/`trexChilyRand`/`trexActivateRay`/`trexRayOrFireHitBox`/
// `trexScrolling`/`trexScrolling2` are set to their real one-time initial
// values only in `gameTrexQuest_init()` (this cartridge's own real
// "power-on" moment, run once per menu launch) and never touched by
// `trexInitGame()` - only `trexBarreDeVie`/`trexTankX`/`trexTankY`/
// `trexScore`/`trexPuissance`/`trexLevelN`/`trexSpeedUp`/`trexCarY` are.
//
// A REAL, PRESERVED UPSTREAM HITBOX BUG: the first of the two real
// trex-vs-"car" collision checks in the alive block compares the TREX
// against `(tankx, CarY)` - the TANK's own real x position paired with the
// separate slow CAR's own real y position, not either object's own real,
// matching (x,y) pair (`(tankx,tanky)` for the tank, or the car's own real
// `(Scrolling2+LCDWIDTH+5, CarY)` for the car). This looks like a genuine
// upstream copy/paste slip, not intentional design - but it's real, load-
// bearing gameplay behavior on real hardware (it does still detect a real
// collision zone, just a mismatched, moving one), so it's preserved
// verbatim below rather than "fixed" into whichever pairing seems more
// sensible.
//
// A REAL, PRESERVED UPSTREAM QUIRK: the apple/chily-eating collision check
// always tests against `pom` (the apple bitmap's own real 16x9 shape),
// never against `chily`, even on the real ticks a chily is the one actually
// drawn on screen (`chilyrand == 5`) - so the hitbox never actually matches
// the chily's own real, different silhouette. Preserved exactly (pom and
// chily share the same real declared 16x9 footprint, so this is a shape
// mismatch, not a size/position one - upstream's own real collision math is
// unaffected either way).
//
// A REAL UPSTREAM COMMENT DISCREPANCY, NOT FIXED: upstream's own README
// and in-code comment both say a chily has "1/10" odds of appearing, but
// the real code rolls `random(1, 10)` (Arduino's own `[min,max)` semantics,
// so real values 1-9 inclusive - 9 possible outcomes, not 10) and only
// treats the single value 5 as "chily" - a genuine 1-in-9 real chance on
// real hardware, not 1-in-10 as documented. Ported as the real
// `1 + arand(9)` roll, matching the actual code exactly rather than the
// comment.
//
// A REAL UPSTREAM REDUNDANCY, SIMPLIFIED WITH ZERO OBSERVABLE EFFECT:
// upstream's own fire-power-bar increment is `puissance++; puissance++;
// puissance--;` inside one `if (puissance < 30)` block - three ops that
// net out to plain `+1` every real time they run (traced through directly,
// not assumed: two increments then one decrement from the same starting
// value always equals one increment). Ported as a single `+ 1` below.
//
// NORMALIZED WITH ZERO OBSERVABLE EFFECT: the real GAME OVER/LEVEL UP text
// (`print(F("Score: "))`/`print(score)` and `print(F("LEVEL: "))`/
// `print(leveln)`) never explicitly sets `cursorX`/`cursorY` of its own
// upstream either - it silently inherits whatever cursor position the
// HUD's own earlier `cursorX=1;cursorY=0;println(score)` last left behind
// on some still-alive previous tick (an incidental leftover, not a
// deliberate layout choice - upstream's own real behavior here was never
// well-defined to begin with, since it depends on exactly which prior tick
// last ran that HUD print). This port instead explicitly sets
// `gbCursorX=0; gbCursorY=0;` right before each of these two real prints,
// matching this whole project's own uniform convention (every other ported
// game explicitly positions its own cursor before every print - see
// gamePong.c/gameFlappyBirdo.c) rather than leaning on an implicit,
// itself-undefined cross-tick carry-over for a purely cosmetic label.
//
// No real `gb.sound.*` calls exist anywhere in trex_quest.ino - this game
// is silent on real hardware, so no sound porting was needed at all.
// `gb.pickRandomSeed()` became `gbPickRandomSeed()` (a documented no-op -
// see this project's own established precedent). `gb.battery.show = false;`
// was dropped outright (purely cosmetic on real hardware, irrelevant here).
// No `setFont()` call exists upstream either, so this game just inherits
// this shim's own real `gbFont3x5` default, matching every other font-
// silent ported game in this project.

